// چهار ماژولِ خالص دادهٔ زبانیِ خودشان را دارند و هر چهار باید **با هم** و **یک بار**
// سرِ boot پیکربندی شوند. این فایل فقط همان چهار فراخوانی است و هیچ منطقی ندارد.
//
// ⚠️ چرا یک ماژولِ جدا و نه چهار فراخوانی در `index.js`: آزمایشگاهِ خوانش هم باید
// **دقیقاً همان** پیکربندی را بگیرد، وگرنه چیزی را می‌سنجد که کاربر نمی‌بیند. سناریوی
// واقعیِ خرابی اگر آزمایشگاه یکی را جا بیندازد:
//   • `configureVerdict` جا بیفتد → `headlineOk` هر سرخطِ غیرفارسی را رد می‌کند →
//     هر ۵ تلاشِ هر فال می‌سوزد → یک دورِ کاملاً صفر با هزینه‌ی کامل، که شبیهِ
//     «این مدل برای روسی بد است» به نظر می‌رسد. یعنی نتیجه‌گیریِ غلط از باگِ خودمان.
//   • `configureCardData` جا بیفتد → سنجه‌ی «لنگر» صفر می‌دهد (مدل «Шут» می‌نویسد و
//     سنجه دنبالِ «دیوانه» می‌گردد)، یعنی مرکزی‌ترین متریکِ کیفیت بی‌معنی می‌شود.
//   • `configureRepair` جا بیفتد → پرامپتِ فارسیِ تعمیر روی متنِ روسی اجرا می‌شود.
// همان درسِ `--dry` و `decideReceipt`: هرچه دو مصرف‌کننده دارد باید یک منبع داشته باشد.
//
// ⚠️ این‌جا زندگی می‌کند و نه در `reading-core.js`، چون `repair.js` از خودِ
// `reading-core.js` import می‌کند و برعکسش یک حلقه‌ی import می‌ساخت.
//
// برای `fa` هیچ‌کدام از این جدول‌ها در locale نیستند (به‌جز `verdict`)، پس هر ماژول به
// پیش‌فرضِ فارسیِ هاردکدِ خودش fallback می‌کند و رفتارِ فارسی بیت‌به‌بیت دست‌نخورده است.
import { configureVerdict } from './verdict.js';
import { configureSeparator } from './reading-core.js';
// ⚠️ صرفاً برای اثرِ جانبیِ بارگذاری: `repair.js` لغتنامه‌اش را خودش از `LANG_DATA`
// برمی‌دارد. import اش این‌جاست تا این فایل واقعاً «همه‌ی پیکربندیِ زبان» باشد و کسی
// دنبالِ یک نقطه‌ی پیکربندیِ دوم نگردد.
import './repair.js';

export function configureLocale(L) {
  configureVerdict(L?.verdict);
  // آرگومانِ دوم جداکننده‌ی نام از سرخط است؛ نبودنش یعنی «همان ویرگولِ همین زبان»،
  // پس یک زبان نمی‌تواند نصفه پیکربندی شود و «Аня، …» دوباره برگردد.
  configureSeparator(L?.verdict?.dashReplacement, L?.verdict?.nameSeparator);
}

// 🎴 گنجینه — متنِ از-پیش-نوشته‌ی کارتِ روز، بر اساسِ **ماهِ تولد**.
//
// قاعده‌ی آهنین (تصمیمِ صریحِ مالک، ۱۴۰۵/۰۵/۲۷): کارتِ روز **هرگز** با LLM ساخته نمی‌شود.
// نه فراخوانیِ زنده، نه فالبک، نه «فقط این یک بار». دلیلش هم اقتصاد است و هم کیفیت:
// کارتِ روز رایگان است و روزی یک بار برای **هر** کاربر اجرا می‌شود، یعنی تنها مسیری که
// هزینه‌اش با تعدادِ کاربر خطی بالا می‌رود بدونِ اینکه درآمدی پشتش باشد. متنِ از پیش
// نوشته‌شده هم ارزان‌تر است، هم قابلِ بازبینیِ انسانی، هم همیشه همان کیفیت را می‌دهد.
//
// چرا JSON و نه جدولِ SQLite: این متن‌ها **محتوا** اند نه دیتای کاربر — نوشته می‌شوند،
// در گیت دیف می‌خورند، ریویو می‌شوند و با deploy می‌روند. دقیقاً مثل `card-knowledge.fa.json`.
// در جدولِ DB نه دیف دارند نه ریویو، و هر اصلاحِ تایپی یک مهاجرت می‌خواهد.
//
// ساختار: { "<ماه ۱..۱۲>": { "<کلیدِ کارت>": ["نسخه‌ی ۱", ...] } }
// ماه‌ها شمسی‌اند (۱ = فروردین). تعدادِ نسخه‌ها **متغیر** است، نه ثابت (پایین).
//
// ⏳ **برنامه‌ی تدریجیِ نسخه‌ها (تصمیمِ صریحِ مالک):**
//   امروز  → **۱ نسخه** per (ماه × کارت) = ۹۳۶ متن. کافی است که فلو راه بیفتد.
//   هفته‌ی بعد → ۲ نسخه. ماهِ بعد → ۳ نسخه.
// نقشِ نسخه‌ی دوم و سوم **پشتیبانِ تکرار** است، نه چرخشِ اصلی: قاعده‌ی عدمِ تکرارِ
// پایین جلوی تکرارِ کارت را می‌گیرد، و اگر با این حال کارتی دوباره درآمد، نسخه‌ی
// بعدی نشان داده می‌شود تا کاربر عینِ همان متن را دوباره نخواند.
//
// کارتی که متن ندارد اصلاً وارد قرعه نمی‌شود (`eligibleCards`)، پس هیچ کاربری به
// متنِ خالی نمی‌خورد و گنجینه می‌تواند ماه‌به‌ماه پر شود.
import { readFileSync } from 'node:fs';
import { logErr } from '../../shared/logger.js';
import { langTable, LANGS } from './locale-ctx.js';

/* 🌍 گنجینه per زبان است، نه مشترک (بند ۲و/۶). دیتای فارسی صریحاً به تقویمِ ایرانی
 * و برجِ همان ماه گره خورده («تو فروردینی»، «ترازو نشانِ خودِ ماهته»)، پس **هرگز**
 * نباید به زبانِ دیگری سرو شود. زبانی که فایلِ خودش را ندارد `DATA` خالی می‌گیرد و
 * فیچر خودکار خاموش می‌شود؛ همان الگوی `hafez.js` و کاملاً graceful (مسیرِ
 * `ganjinehEmpty` از قبل پیام و دکمه‌های قدمِ بعدی دارد).
 * ⚠️ قبل از این، مسیر `daily-ganjineh.fa.json` هاردکد بود، یعنی رباتِ روسی متنِ
 * **فارسی** نشان می‌داد. */
const LOCALE = process.env.LOCALE?.trim() || 'fa';

/* 🌍 per زبانِ زمینه‌ی جاری. یک پروسه‌ی چندزبانه چند گنجینه دارد و زبانی که فایلش
 * نیست (امروز: انگلیسی) آبجکتِ خالی می‌گیرد، یعنی کارتِ روز **فقط برای همان زبان**
 * خاموش می‌شود و بقیه دست‌نخورده می‌مانند. همان الگوی fail-safe قبلی، per زبان. */
const DATA_T = langTable({});
for (const lang of LANGS) {
  try {
    DATA_T.set(lang, JSON.parse(readFileSync(new URL(`./daily-ganjineh.${lang}.json`, import.meta.url), 'utf8')));
  } catch (e) {
    // fail-safe: نبودنِ فایل نباید ربات را بکشد. نتیجه‌اش «هیچ کارتی واجد شرایط نیست» است
    // که خودِ کارتِ روز با پیامِ مؤدبانه هندلش می‌کند.
    DATA_T.set(lang, {});
    logErr(`گنجینه‌ی «${lang}» بارگذاری نشد:`, e.message);
  }
}
const DATA = new Proxy({}, {
  get: (_t, k) => DATA_T.get()[k],
  has: (_t, k) => k in DATA_T.get(),
  ownKeys: () => Reflect.ownKeys(DATA_T.get()),
  getOwnPropertyDescriptor: (_t, k) => Reflect.getOwnPropertyDescriptor(DATA_T.get(), k),
});

// سقفِ نسخه‌ای که سیستم می‌تواند بچرخاند. **تعدادِ واقعیِ هر خانه از خودِ دیتا** خوانده
// می‌شود (`countOf`)، نه از این عدد؛ این فقط سقف است تا نسخه‌ی چهارمِ سهوی نادیده نماند.
export const VARIANTS = 3;

// 🔁 قاعده‌ی عدمِ تکرار — **بر حسبِ «بارِ فال‌گیری»، نه «روز»** (تصمیمِ صریحِ مالک).
// چرا این تمایز حیاتی است: کاربر هر روز فال نمی‌گیرد. با معیارِ روز، کسی که هفته‌ای
// یک بار می‌آید عملاً هیچ محافظتی نداشت (فالِ هفته‌ی پیشش خارج از پنجره بود و می‌توانست
// همان لحظه دوباره بیاید). با معیارِ «۷ بارِ آخر»، محافظت به **تجربه‌ی** کاربر گره
// می‌خورد نه به تقویم: هر کاربری، با هر ریتمی، هفت فالِ متفاوتِ پشتِ‌سرهم می‌بیند.
// کارتی که بیش از این تعداد فال‌گیری از نمایشش گذشته باشد دوباره واجدِ شرایط است و
// انتخابِ دوباره‌اش کاملاً درست است.
export const NO_REPEAT_DRAWS = 7;

/* نامِ ماه عمداً این‌جا نیست: یک متنِ رو-به-کاربر است و از `L.onboarding.birthMonths`
 * همان locale می‌آید (بند ۲و). ایندکسِ ۱..۱۲ بینِ همه‌ی زبان‌ها یکی می‌ماند چون
 * `birth_month` کاربرانِ واقعی رویش نشسته و دیتای گنجینه با همان کلید ذخیره شده. */

/** آیا برای این ماه و این کارت متنی نوشته شده؟ */
export const hasText = (month, cardKey) =>
  Array.isArray(DATA?.[String(month)]?.[cardKey]) && DATA[String(month)][cardKey].length > 0;

/** چند نسخه برای این خانه نوشته شده؟ صفر یعنی نانوشته. */
export const countOf = (month, cardKey) => {
  const arr = DATA?.[String(month)]?.[cardKey];
  return Array.isArray(arr) ? arr.length : 0;
};

/** متنِ نسخه‌ی مشخص. اگر آن نسخه نبود، اولین نسخه‌ی موجود. */
export function textOf(month, cardKey, variant = 0) {
  const arr = DATA?.[String(month)]?.[cardKey];
  if (!Array.isArray(arr) || !arr.length) return '';
  return String(arr[variant] || arr[0] || '').trim();
}

/** چند متن در کلِ گنجینه هست (برای گزارشِ پیشرفتِ نگارش و چکِ CI). */
export function stats() {
  let months = 0, cards = 0, texts = 0;
  for (const m of Object.keys(DATA || {})) {
    if (m.startsWith('_')) continue;   // کلیدهای توضیحی، نه ماه
    months++;
    for (const k of Object.keys(DATA[m] || {})) {
      cards++;
      texts += (DATA[m][k] || []).length;
    }
  }
  return { months, cards, texts };
}

/**
 * کارت‌هایی که **امروز** می‌توانند برای این کاربر بیایند.
 *
 * دو شرط، هر دو لازم:
 *   ۱) در `recentKeys` نباشد — یعنی جزوِ **۷ بارِ آخرِ فال‌گیریِ همین کاربر** نباشد
 *      (نه ۷ روزِ اخیر؛ دلیلش بالای فایل). این تضمین می‌کند هر کاربری، با هر ریتمی،
 *      هفت فالِ پشتِ‌سرهمِ **متفاوت** می‌بیند. در بارِ هشتم کارتِ اول دوباره وارد قرعه
 *      می‌شود، ولی انتخابش شانسی است نه چرخشی، و درآمدنش کاملاً درست است.
 *      ⚠️ اگر کاربر تا حالا فقط ۲ یا ۳ بار فال گرفته، همان ۲ یا ۳ کارت حذف می‌شوند
 *      (صدازننده فقط «آخرین ۷ ردیف» را می‌دهد؛ کمتر بودنشان خودبه‌خود درست کار می‌کند).
 *   ۲) برای ماهِ تولدِ او متن داشته باشد — وگرنه کاربر به متنِ خالی می‌خورد. تا وقتی
 *      گنجینه کامل نشده، همین شرط عملاً قرعه را محدود به کارت‌های نوشته‌شده می‌کند.
 *
 * اگر هیچ کارتی نماند (گنجینه‌ی خیلی کوچک)، شرطِ ۷ روز کنار گذاشته می‌شود — چون
 * «تکرارِ کارت» از «کارتِ روزِ نداشتن» بهتر است. صفر برگرداندن یعنی گنجینه‌ی آن ماه خالی است.
 */
export function eligibleCards(allKeys, month, recentKeys = []) {
  const recent = new Set(recentKeys);
  const written = allKeys.filter((k) => hasText(month, k));
  const fresh = written.filter((k) => !recent.has(k));
  return fresh.length ? fresh : written;
}

/**
 * کدام نسخه‌ی این کارت به این کاربر نشان داده شود.
 *
 * قاعده: نسخه‌ای که **ندیده**. اگر چند نسخه‌ی ندیده مانده، شانسی از بینشان؛ اگر همه را
 * دیده، شانسی از کلِ نسخه‌ها (چرخه بسته شده).
 *
 * ⚠️ `count` **تعدادِ واقعیِ نسخه‌های همان خانه** است، نه ثابتِ `VARIANTS`. تا قبل از این،
 * تابع بدونِ توجه به دیتا عددِ ۰ یا ۱ یا ۲ برمی‌گرداند و `textOf` به متنِ اول فالبک
 * می‌کرد؛ یعنی کاربر متنِ درست را می‌دید ولی `daily_log.variant` عددی ثبت می‌شد که
 * هرگز نمایش داده نشده بود. با ۱ نسخه (وضعیتِ امروز) این یعنی **دو سومِ ردیف‌های
 * دفتر دروغ بودند**، و بعد از افزودنِ نسخه‌ی ۲ و ۳ همان دروغ باعث می‌شد متنِ خوانده‌شده
 * دوباره به‌عنوان «ندیده» نشان داده شود.
 *
 * `rand` تزریق می‌شود تا تست قطعی باشد.
 */
export function pickVariant(seenVariants = [], count = VARIANTS, rand = Math.random) {
  const n = Math.max(1, Math.min(VARIANTS, Math.floor(Number(count)) || 1));
  const seen = new Set(seenVariants.map(Number));
  const all = Array.from({ length: n }, (_, i) => i);
  const unseen = all.filter((v) => !seen.has(v));
  const pool = unseen.length ? unseen : all;
  return pool[Math.floor(rand() * pool.length) % pool.length];
}

export default DATA;

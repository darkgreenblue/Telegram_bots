// ключи существуют ради единой формы locale — как и весь блок invoice выше.
const PACK_NAMES = { basic: 'Горсть', gold: 'Мешочек', magic: 'Сундук', legend: 'Легендарный', eternal: 'Вечный' };
const packName = (p) => PACK_NAMES[p?.key] || '';

/* Как зовётся «место, где лежит баланс». Одна русская форма не может стоять во всех
 * падежах, поэтому helper отдаёт именительный/винительный мн. ч. («алмазы»), а фразы
 * строятся вокруг него: «Твои алмазы: 5💎», «алмазы списаны». Родительный и дательный
 * («алмазов», «алмазам») секции пишут прямо в тексте. */
const purse = (cur) => (cur?.on ? 'алмазы' : 'кошелёк');
// Строка «текущий баланс»: короткая слитная форма, потому что название единицы уже
// стоит во фразе и повтор («алмазы: 5 алмазов») читается плохо.
const purseLine = (balance, cur) => (cur?.on ? `Твои ${purse(cur)}: ${moneyTight(balance, cur)}` : `Твой ${purse(cur)}: ${moneyLong(balance, cur)}`);

// Цитатный блок Telegram: рендерится только с `parse_mode: 'HTML'`.
const quote = (s) => `<blockquote>${s}</blockquote>`;
const purseQuote = (balance, cur) => {
  const line = `💠 ${purseLine(balance, cur)}`;
  return cur?.on ? quote(line) : line;
};



const fmt = (n) => Number(n).toLocaleString('ru-RU');

/* 🇷🇺 صرفِ عددیِ روسی. یک رشته‌ی واحد نمی‌تواند «۱ الماس / ۲ الماس / ۵ الماس» را درست
 * بدهد (روسی سه شکل دارد و ۱۱ تا ۱۴ استثنا هستند)، پس هر عبارتِ شمارشی از این دو
 * helper می‌آید و هیچ‌جا «алмаз» خام بعد از عدد نوشته نمی‌شود. */
const plural = (n, [one, few, many]) => {
  const m10 = n % 10, m100 = n % 100;
  if (m10 === 1 && m100 !== 11) return one;
  if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
  return many;
};
const coins = (n) => `${fmt(n)} ${plural(n, ['алмаз', 'алмаза', 'алмазов'])}`;

/* ---- Внутренняя валюта ----
 * Внутри базы баланс хранится в базовых единицах; «алмаз» это единица ОТОБРАЖЕНИЯ.
 * `cur` собирает index.js: { on, value, name, emoji }.
 * В русской версии алмазная экономика включена ВСЕГДА, поэтому ветка `cur.on === false`
 * мёртвая. Она сохранена только ради сигнатуры и печатает то же число с 💎: так она
 * физически не может выдать пользователю несклоняемое «алмаз» после числа. */
const money = (toman, cur) =>
  (cur?.on ? `${fmt(Math.round(Number(toman) / cur.value))} ${cur.emoji}` : `${fmt(toman)} 💎`);
// Длинная форма (с названием единицы): для мест, где пользователь видит валюту впервые.
// Число всегда через coins(), иначе вышло бы «30 алмаз».
const moneyLong = (toman, cur) =>
  (cur?.on ? `${coins(Math.round(Number(toman) / cur.value))} ${cur.emoji}` : `${fmt(toman)} 💎`);
// Слитная форма «5💎», без пробела между числом и эмодзи: строка баланса и подписи кнопок.
const moneyTight = (toman, cur) =>
  (cur?.on ? `${fmt(Math.round(Number(toman) / cur.value))}${cur.emoji}` : `${fmt(toman)}💎`);

/* 📦 Отображаемые имена наборов. Ключи (`basic`/`gold`/`magic`) лежат в
 * `payments.package_key` у реальных пользователей и не меняются никогда;
 * переводится только отображаемое имя. */

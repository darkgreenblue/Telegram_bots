// 🌍 تک‌نقطه‌ی بارگذاریِ `.env` — و **باید اولین import ربات باشد**.
//
// چرا یک ماژولِ سه‌خطی لازم شد (باگِ واقعی، بازتولیدشده):
// در ESM همه‌ی importهای ایستا **قبل از** اولین خطِ بدنه‌ی همان ماژول evaluate
// می‌شوند. پس وقتی `index.js` این شکل را داشت:
//
//     import dotenv from 'dotenv';
//     dotenv.config({ path: process.env.ENV_FILE || '.env' });   ← بدنه
//     import { … } from './reading-core.js';                     ← هویست می‌شود
//
// `reading-core.js` زودتر اجرا می‌شد و `process.env.LOCALE` را **خالی** می‌دید،
// چون pm2 فقط `ENV_FILE` را در محیطِ واقعی می‌گذارد و خودِ `LOCALE` تازه با همان
// `dotenv.config()` از فایل می‌آمد. یعنی رباتِ روسی/پرتغالی/اسپانیایی به fa
// برمی‌گشت و سه چیز را **بی‌صدا** از دست می‌داد:
//   • `card-knowledge.fa.json` → جدولِ دانشِ **فارسی** داخلِ یک پرامپتِ روسی
//   • `langdata.<locale>.json` → خالی، یعنی نامِ کارت‌ها فارسی، **گاردهای ضعفِ
//     زبانی (جنسیت و خطابِ رسمی) اصلاً وجود نداشتند**، و ریشه‌ی جهت در
//     `headlineOk` غایب بود
//   • `daily-ganjineh.fa.json` → متنِ **فارسیِ** کارتِ روز برای کاربرِ روس
// هیچ خطایی هم نمی‌داد: هر سه مسیر عمداً fail-safe اند.
//
// فارسی از این باگ آسیب نمی‌دید و از این فیکس هم تغییری نمی‌کند، چون fallbackِ
// همان مسیرها دقیقاً `fa` است. یعنی رباتِ زنده بیت‌به‌بیت دست‌نخورده می‌ماند.
//
// ⚠️ `tools/reading-lab.mjs` همین تله را دیده بود و با importهای **پویا** حلش
// کرده بود (کامنتِ بالای همان بلوک صریح می‌گوید «ترتیبِ این بلوک عمدی و شکننده
// است»). یعنی ابزار درست شده بود و خودِ محصول نه. این ماژول همان تضمین را برای
// ربات می‌دهد، بدونِ اینکه importهای `index.js` مجبور به پویا شدن باشند.
//
// گاردِ CI: `tools/check-env-boot.mjs` — هم رفتاری (یک پروسه‌ی واقعیِ node با
// `ENV_FILE` و بدونِ `LOCALE`)، هم ساختاری (این باید اولین importِ `index.js` باشد).

// نامِ نمایشیِ چیدمان بر اساس نسلِ کاتالوگی که کاربر می‌بیند.
export const faOf = (s, v2, v3) => ((v3 && s?.faV3) || (v2 && s?.faV2) || s?.fa || '');

/** کاتالوگی که به این کاربر نشان داده می‌شود (v2 = کاتالوگ عشق‌محورِ تقابلی). */
export const spreadsFor = (v2) => (v2 ? SPREADS_V2 : SPREADS);

/**
 * موضوعِ یک آی‌دیِ چیدمان — برای پیشنهاددهنده و آنالیتیکس.
 * چیدمان‌های نسل‌های قبل خودشان `topic` ندارند، پس از روی `focus`/`id` حدس زده می‌شوند
 * تا سابقه‌ی کاربرِ قدیمی هم در قاعده‌ی «چیزی که تازه گرفته دوباره پیشنهاد نشود» بشمارد.
 */
export function topicOf(spreadId) {
  const s = SPREAD_BY_ID[spreadId];
  if (!s) return null;
  if (s.topic) return s.topic;
  if (TOPIC_BY_KEY[s.id]) return s.id;              // love/yesno/choice/career/money/crush/commit
  if (s.open) return 'personal';                     // open3/open5/open10
  return null;                                       // three/celtic/inner/family/… موضوعِ نسل جدید ندارند
}

/**
 * موضوعِ یک چیدمان **برای آنالیتیکس** — مثل `topicOf` ولی هرگز خالی نمی‌ماند.
 *
 * چرا جدا از `topicOf`: آن یکی منطقِ محصول است (جریمه‌ی تازگیِ پیشنهاددهنده) و باید برای
 * چیدمانی که موضوعِ نسل جدید ندارد `null` بدهد، وگرنه `three` به‌زور به یک موضوع نگاشت
 * می‌شود و پیشنهادِ اشتباه می‌سازد. ولی در رویدادِ `spread_selected` همان `null` به رشته‌ی
 * خالی تبدیل می‌شد و ۱۴ انتخاب در پنجره‌ی تحلیلِ ۴ شهریور ۱۴۰۵ زیرِ کلیدِ `''` گم شدند.
 * حالا صریح می‌گوید کدام چیدمانِ بازنشسته بوده (`legacy:three`)، پس گروه‌بندیِ داشبورد
 * روی `topic` کامل می‌ماند. رویدادهای قدیمیِ `''` دست‌نخورده‌اند (بند ۲ج/۳: فقط اضافه).
 */
export const topicForAnalytics = (spreadId) => topicOf(spreadId)
  || (SPREAD_BY_ID[spreadId] ? `legacy:${spreadId}` : 'unknown');


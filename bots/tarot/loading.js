// 🕯 نشانگرِ انتظار — پنج طرح، یک انتخاب.
//
// چرا یک ماژولِ جدا: مالک صریح گفت «اگه بتونی کارش رو در بیاری، جاهای دیگه هم لازم دارم».
// پس این‌جا هیچ متنِ تاروتی هاردکد نشده؛ برچسب از بیرون می‌آید و هر ربات دیگری می‌تواند
// همین را import کند. هیچ وابستگیِ npm ندارد و کاملاً خالص است، پس تست هم می‌شود.
//
// ── محدودیت‌هایی که شکلِ همه‌ی طرح‌ها را تعیین کرده‌اند ───────────────────────────
// ۱) هر فریم یک `editMessageText` است، یعنی یک ریکوئستِ API. سقفِ نقل‌شده‌ی تلگرام برای
//    پیام به **یک** چت حدود ۱ در ثانیه است و عبور از آن ۴۲۹ می‌دهد. یک فالِ ده‌کارتی
//    می‌تواند ۶۰ ثانیه طول بکشد، پس «سریع‌تر» نمی‌تواند یعنی «۵۰۰ میلی‌ثانیه تا ابد».
// ۲) متن **راست‌به‌چپ** است. هر انیمیشنی که به حرکتِ چپ‌به‌راست تکیه کند، کنارِ متنِ
//    فارسی برعکس یا پرشی خوانده می‌شود. راه‌حلِ همه‌ی طرح‌های این‌جا یکی است: نوار در
//    **خطِ خودش** و از کاراکترهای **خنثی** ساخته می‌شود، پس جهتِ پاراگراف را می‌گیرد و
//    برای خواننده‌ی فارسی از راست پر می‌شود — که همان جهتِ درست است.
// ۳) **عرضِ همه‌ی فریم‌ها باید یکی باشد**، وگرنه پیام در هر فریم جابه‌جا می‌شود و حس
//    خرابی می‌دهد. برای همین هر طرح در هر فریم دقیقاً همان تعداد نویسه را می‌سازد و
//    از variation selector (مثل `▪️`) استفاده نمی‌شود که روی کلاینت‌ها فرق می‌کند.
// ۴) بند ۱۰ ریشه: هیچ خطِ تیره‌ی بلندی در متنِ رو-به-کاربر.
//
// ── ایرادِ نسخه‌ی قبلی (به زبانِ خودِ مالک) ────────────────────────────────────
// «خیلی سریع‌تر ادیت بشه، اگه نمیشه گرافیکش عوض بشه چون الان توی مدتی که هست فقط ۲ تا
// مربع سفید میاد و اصن معلوم نیست ویتینگه». هر دو ایراد درست بود: با ۳۰۰۰ms و یک الگوی
// ۵ فریمی، در ده ثانیه‌ی اولِ انتظار فقط سه فریم دیده می‌شد.

const BAR = 6;   // طولِ نوار در طرح‌های نواری (ثابت، تا عرضِ فریم‌ها یکی بماند)

/** تکرارِ امن: هرگز رشته‌ی با طولِ منفی نمی‌سازد. */
const rep = (ch, n) => ch.repeat(Math.max(0, n));

/* ── A) نوارِ پرشونده ───────────────────────────────────────────────────────────
   ساده‌ترین و بی‌ریسک‌ترین. دو نویسه‌ی هم‌عرض از بلوکِ Geometric Shapes Extended که
   هر دو Emoji_Presentation دارند، پس روی هر کلاینتی هم‌اندازه‌اند و variation selector
   لازم ندارند. پر شدن **حرکت** است، نه فقط چشمک، و کاربر در دو ثانیه سه پله می‌بیند. */
const bar = (label) => (i) => {
  const n = i % (BAR + 1);
  return `${label}\n${rep('⬛', n)}${rep('⬜', BAR - n)}`;
};

/* ── B) مرحله‌های کار ──────────────────────────────────────────────────────────
   تنها طرحی که واقعاً **پیشرفت** را می‌گوید، نه فقط «زنده‌ام». برای انتظارِ تا ۶۰ ثانیه
   بهترین است، چون کاربر می‌فهمد کار جلو می‌رود و منتظرِ چیزِ مشخصی است. مرحله‌ها
   جلو می‌روند و روی آخری می‌مانند (عقب نمی‌روند، وگرنه دروغ می‌شود). */
const PHASES_FA = ['کارت‌ها رو کنار هم می‌چینم', 'معنی‌هاشون رو می‌خونم', 'جوابت رو می‌نویسم'];
const phases = (list = PHASES_FA, everyFrames = 6) => (i) => {
  const p = Math.min(list.length - 1, Math.floor(i / everyFrames));
  const dots = rep('·', (i % 3) + 1) + rep(' ', 2 - (i % 3)); // فاصله‌ی رقمی: عرض ثابت
  return `${list[p]} ${dots}`;
};

/* ── C) چرخانِ ماه ─────────────────────────────────────────────────────────────
   چرخش، یعنی بی‌درنگ «در حالِ کار». چهار جایگزین سنجیده شد و رد شد:
     • اسپینرِ بریل (⠋⠙⠹…): روی خیلی از فونت‌های موبایل به مربع یا نویسه‌ی خیلی ریز
       می‌افتد و اصلاً حرکت دیده نمی‌شود.
     • ساعت‌های 🕐…🕛: دوازده فریم و عقربه‌ها در اندازه‌ی چت تشخیص‌ناپذیرند.
     • فِلِش‌ها (←↑→↓): جهت‌دارند، یعنی دقیقاً چیزی که در RTL خراب می‌شود.
     • ◐◑◒◓: عرضشان روی کلاینت‌ها یکسان نیست.
   ماه هشت فریم دارد، هر فریم یک اموجیِ تک با عرضِ یکسان، و به‌علاوه با جهانِ محصول
   می‌خواند. */
const MOON = ['🌑', '🌒', '🌓', '🌔', '🌕', '🌖', '🌗', '🌘'];
const moon = (label) => (i) => `${MOON[i % MOON.length]} ${label}`;

/* ── D) ورق خوردنِ کارت ────────────────────────────────────────────────────────
   تاروت-محور: سه کارتِ پشت‌رو که یکی‌یکی رو می‌شوند و دوباره برمی‌گردند. تنها طرحی
   که خودش بخشی از آیینِ محصول است. ریسکش این است که «ورق خوردن» را می‌شود با
   «کارت‌هات آماده شد» اشتباه گرفت، برای همین برچسب کنارش اجباری است. */
const flip = (label) => (i) => {
  const n = i % 4;
  return `${label}\n${rep('🎴', n)}${rep('🂠', 3 - n)}`;
};

/* ── E) هیبرید با شتابِ متغیر ──────────────────────────────────────────────────
   طرحِ پیشنهادی. دقیقاً به ایرادِ مالک جواب می‌دهد بدونِ اینکه ۶۰ ادیت پشتِ‌سرهم بزند:
   یک عنصرِ **همیشه در حرکت** (ماه، هر فریم عوض می‌شود → «زنده است») به‌علاوه‌ی یک
   عنصرِ **درشت‌تر** (نوار، هر دو فریم یک پله → «جلو می‌رود»)، و مرحله‌ی کار در متن.
   شتابِ متغیر در `pace` پایین است، نه در خودِ فریم. */
const hybrid = (list = PHASES_FA) => (i) => {
  const p = Math.min(list.length - 1, Math.floor(i / 8));
  const n = Math.floor(i / 2) % (BAR + 1);
  return `${MOON[i % MOON.length]} ${list[p]}\n${rep('⬛', n)}${rep('⬜', BAR - n)}`;
};

/* ── ضرب‌آهنگ ─────────────────────────────────────────────────────────────────
   کلیدِ حلِ تناقضِ «سریع‌تر» با «۴۲۹ نگیر»: انتظار یکنواخت نیست. کاربر در ثانیه‌های
   اول تصمیم می‌گیرد که «کار می‌کند یا خراب است»، و بعد از آن فقط منتظر می‌ماند. پس
   ده ثانیه‌ی اول تند می‌رویم و بعد آرام. برای یک انتظارِ ۶۰ ثانیه‌ای این یعنی حدود
   ۱۰ + ۲۵ = ۳۵ ادیت، در برابرِ ۶۰ ادیتِ حالتِ «یک‌ثانیه‌ایِ ثابت» و در برابرِ ۲۰ ادیتِ
   نسخه‌ی قبلی که کند دیده می‌شد. یعنی هم حسِ سرعت، هم فاصله‌ی امن تا سقف. */
export const FAST_MS = 900;
export const SLOW_MS = 2000;
export const FAST_FOR_MS = 10_000;
/** فاصله‌ی فریمِ بعدی بر حسبِ زمانِ سپری‌شده از شروعِ انتظار. */
export const pace = (elapsedMs) => (elapsedMs < FAST_FOR_MS ? FAST_MS : SLOW_MS);

/** پنج طرح، برای آزمایشِ زنده. `frames(label)` یک تابعِ `(i) => string` می‌دهد. */
export const LOADERS = {
  bar:    { fa: 'A) نوارِ پرشونده',        frames: bar },
  phases: { fa: 'B) مرحله‌های کار',        frames: () => phases() },
  moon:   { fa: 'C) چرخانِ ماه',           frames: moon },
  flip:   { fa: 'D) ورق خوردنِ کارت',      frames: flip },
  hybrid: { fa: 'E) هیبرید (پیشنهادی)',    frames: () => hybrid() },
};

/** طرحِ فعالِ ربات. عوض کردنش **یک کلمه** است. */
export const ACTIVE = 'hybrid';

/** فریمِ آماده‌ی مصرف در ربات. `label` متنِ رو-به-کاربر است، پس در locale می‌ماند. */
export const loadingFrame = (label) => LOADERS[ACTIVE].frames(label);

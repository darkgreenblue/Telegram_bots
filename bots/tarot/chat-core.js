/* ⚠️ `guard: false` **فقط** برای آزمایشگاه است و مصرفش در محصول ممنوع: سنجه باید
 * برچسبِ خامِ مدل را ببیند تا بشود فهمید قاعده‌ی پرامپت چقدر جواب داده. اگر سنجه هم
 * نسخه‌ی گاردخورده را می‌دید، همیشه صفر گزارش می‌کرد و ما فکر می‌کردیم مسئله حل شده،
 * در حالی که فقط **پنهان** شده بود (بند ۶ب-۲ ریشه). */
export function cleanFollowUp(raw, { max = CHAT_FOLLOWUP_MAX, guard = true } = {}) {
  let s = String(raw ?? '').replace(/\s+/g, ' ').trim();
  s = s.replace(/^["'«»“”]+/, '').replace(/["'«»“”]+$/, '').trim();
  if (!s || s.length > max) return '';
  return guard && followUpBad(s) ? '' : s;
}

/* باقی‌مانده‌ی برچسب بعد از برداشتنِ واژه‌های تأیید. زیرِ این مقدار یعنی برچسب هیچ
 * محتوایی ندارد و تپش یک پیامِ توخالی می‌فرستد. «آره، ولی چرا کارتِ دوم برعکس بود؟»
 * از این گارد رد می‌شود چون باقی‌مانده‌اش یک سؤالِ کامل است. */
export const FU_ASSENT_REST = 12;
/** کلاسِ خرابیِ برچسب (`'meta'` | `'assent'`)، یا `''` اگر سالم باشد. */
export function followUpBad(label) {
  const n = norm(label);
  if (!n) return '';
  for (const p of LANG.followUpMeta) { const q = norm(p); if (q && n.includes(q)) return 'meta'; }
  let rest = n, stripped = false;
  const words = LANG.followUpAssent.map(norm).filter(Boolean).sort((a, b) => b.length - a.length);
  for (let i = 0; i < 4; i++) {
    const hit = words.find((w) => rest === w || rest.startsWith(`${w} `));
    if (!hit) break;
    rest = rest.slice(hit.length).trim();
    stripped = true;
  }
  if (stripped && rest.length < FU_ASSENT_REST) return 'assent';
  return '';
}

/* ═══ ✂️ سقفِ برچسبِ دکمه‌ی سؤالِ پیشنهادی (از ۱۴۰۵/۰۶/۲۹) ═══
 *
 * خواسته‌ی صریحِ مالک: «حتماً محدودیت داشته باشه، محدودیت کاراکتر داشته باشه» — چون
 * «یه بخشیش از دکمه می‌زنه بیرون و قابلِ خوندن نیست».
 *
 * ⚠️ Bot API هیچ سقفی برای طولِ برچسبِ دکمه **اعلام نکرده**؛ بریدگی یک اتفاقِ رندرِ
 * کلاینت است. پس این دو عدد از **مشاهده‌ی خودِ مالک** می‌آیند نه از مستندات: برچسبِ
 * ۳۷نویسه‌ای را تأیید کرد و ۴۱نویسه‌ای به بالا را رد. مرزِ عملی ~۳۸ تا ۴۰ است.
 *
 * 🔑 دو عدد، عمداً متفاوت و هر دو این‌جا (تک‌منبع، وگرنه پرامپت و کد بی‌صدا واگرا
 * می‌شوند): `PROMPT` سقفی است که **پرامپت** از مدل می‌خواهد و سخت‌گیرتر است تا برچسبِ
 * معمولی هیچ‌وقت به مرزِ بریدن نزدیک نشود؛ `BTN` سقفِ **نمایشیِ** کد است، یعنی تورِ
 * ایمنی برای وقتی مدل از قاعده رد می‌شود. کارِ اصلی را پرامپت می‌کند، نه این تابع. */
export const CHAT_FU_PROMPT_MAX = 36;
export const CHAT_FU_BTN_MAX = 40;
/** برچسبِ نمایشیِ دکمه. **سؤالِ ذخیره‌شده را لمس نمی‌کند**، فقط نمایش را می‌بُرد. */
export function chatBtnLabel(s) {
  const t = String(s || '').trim();
  if (t.length <= CHAT_FU_BTN_MAX) return t;
  const head = t.slice(0, CHAT_FU_BTN_MAX - 1);
  const sp = head.lastIndexOf(' ');
  const keep = sp >= Math.floor(CHAT_FU_BTN_MAX * 0.6) ? head.slice(0, sp) : head;
  return `${keep.trimEnd()}…`;
}

/** پاکت را باز می‌کند. `null` یعنی غیرقابلِ استفاده ⟵ `validate` رد می‌کند ⟵ retry. */
export function parseChatOut(raw) {
  let o = null;
  try { o = parseJsonLoose(String(raw || '')); } catch { o = null; }
  if (!o || typeof o !== 'object' || Array.isArray(o)) return null;
  const text = String(o[CHAT_OUT_KEYS.text] ?? '').trim();
  if (text.length < CHAT_MIN_CHARS || text.length > CHAT_HARD_CHARS) return null;
  // برچسبِ خام (فقط پاکسازیِ شکلی) و برچسبِ گاردخورده کنارِ هم برمی‌گردند: محصول از
  // `followUp` می‌خواند و آزمایشگاه از `followUpRaw` + `fuBad` (بالا توضیح داده شده).
  const fuRaw = cleanFollowUp(o[CHAT_OUT_KEYS.followUp], { guard: false });
  const fuBad = fuRaw ? followUpBad(fuRaw) : '';
  // پیشنهاد: یک خط، بدونِ گیومه‌ی دورگیر. خالی یا بلندتر از سقف ⟵ «پیشنهادی نداد».
  let offer = noDash(String(o[CHAT_OUT_KEYS.offer] ?? '')).replace(/\s+/g, ' ').trim()
    .replace(/^["'«“]+/, '').replace(/["'»”]+$/, '').trim();
  if (offer.length > CHAT_OFFER_MAX) offer = '';
  return {
    text,
    offer,
    newReading: truthy(o[CHAT_OUT_KEYS.reading]),
    support: truthy(o[CHAT_OUT_KEYS.support]),
    followUp: fuBad ? '' : fuRaw,
    followUpRaw: fuRaw,
    fuBad,
    end: truthy(o[CHAT_OUT_KEYS.end]),
  };
}

/* 💰 گاردِ فکتِ پولی (تصمیمِ صریحِ مالک، ۱۴۰۵/۰۶/۲۲).
 *
 * ⚠️ **رقم به‌تنهایی شرطِ کافی نیست** (تأکیدِ صریحِ مالک). جوابِ سالم پر از عدد است:
 * «کارت ۳»، «این ۲ کارت»، «در ۳ هفته‌ی آینده». گارد فقط وقتی می‌افتد که یک واژه‌ی
 * **واحدِ پول** و یک **رقم** در یک پنجره‌ی ۱۶ نویسه‌ای کنارِ هم بیایند.
 *
 * ⚠️ و روی عددِ **حرفی** هرگز نمی‌نشیند: نامِ کارت‌ها («ده شمشیر»، «هشت سکه») عددِ
 * حرفی‌اند و گاردِ حرفی هر جوابِ سالمی را قرمزِ کاذب می‌کرد — همان درسِ «پهن‌کردنِ
 * گارد رایگان نیست» (بند ۲و/۶ب-۲ ریشه). */
/* ⚠️ **تومان و ریال عمداً بیرون‌اند** (اندازه‌گیریِ ۱۴۰۵/۰۶/۲۲، بعد از سؤالِ مالک
 * «چرا باید همچین اتفاقی بیفته وقتی ریترای و فالبک داریم؟»).
 *
 * نسخه‌ی اول آن‌ها را داشت و دیتا نشان داد خالص‌منفی است:
 *   • روی **۶ از ۶** جوابِ بدِ واقعیِ آن دور **صفر** گرفت، چون آن‌ها عددی نداشتند و
 *     دروغِ **کیفی** بودند («فال گرفتن از من رایگانه»). گاردِ عددی این کلاس را
 *     ساختاراً نمی‌بیند؛ دفاعِ واقعی همان پرچم + قاعده‌ی پرامپت است.
 *   • و روی فالِ **«کار و پول»** قرمزِ کاذب می‌داد: کاربر در سؤالش «۳۰ میلیون تومان»
 *     گفته و جوابِ سالم نقلش می‌کند. چون هر چهار پله همان کانتکست را می‌بینند این
 *     شکست **هم‌بسته** است، پس retry نجاتش نمی‌دهد و به ریفاند می‌رسد.
 *
 * «الماس/ستاره» واحدِ **خودِ ما** است و در یک فالِ عشق یا کار تقریباً هرگز کنارِ رقم
 * نمی‌آید، پس سطحِ قرمزِ کاذبش ~صفر است. یعنی این گارد از این به بعد فقط بیمه‌ی
 * ثانویه است، نه دفاعِ اصلی. */
const MONEY_WORD = /(الماس|ستاره|استارز)/g;
const ANY_DIGIT = /[۰-۹٠-٩0-9]/;
export function moneyClaimIn(text) {
  const t = String(text || '');
  for (const m of t.matchAll(MONEY_WORD)) {
    const win = t.slice(Math.max(0, m.index - 16), m.index + m[0].length + 16);
    if (ANY_DIGIT.test(win)) return win.trim();
  }
  return '';
}

/** مسیرِ ۱ — **صحتِ پاکت**. کاملاً مستقل از گاردِ فکت (تأکیدِ صریحِ مالک: «این یه مسیر
 *  دیگه هست کلا»). خرابیِ JSON ⟵ retry. */
export const chatEnvelopeOk = (out) => !!parseChatOut(out);

/* ⛔ **گاردِ فکتِ پولی از پروداکشن حذف شد** (تصمیمِ صریحِ مالک، ۱۴۰۵/۰۶/۲۲):
 * «گارد فقط وقتی گاردِ درستی هست که ۱۰۰ درصد مطمئن باشیم ترکیبِ آن کلمات همان معنی
 * را می‌دهد که دنبالشیم؛ در غیرِ این صورت گارد بی‌خودی است و نباید باشد، همان مدل
 * بهتر و قابلِ اطمینان‌تر است.»
 *
 * و دیتا هم همین را می‌گفت، پس این یک سلیقه نیست:
 *   • روی **۶ از ۶** جوابِ بدِ واقعی **صفر** گرفت (آن‌ها رقم نداشتند؛ دروغِ **کیفی**
 *     بودند مثل «فال گرفتن از من رایگانه»).
 *   • و یک مسیرِ **ریفاندِ کاذب** باز می‌کرد: قرمزِ کاذبِ ناشی از کانتکست در هر چهار
 *     پله‌ی `CHAT_PLAN` **هم‌بسته** می‌افتد، پس retry نجاتش نمی‌داد.
 * ارزشِ مشاهده‌شده صفر، ضررِ ممکن غیرِصفر ⟵ حذف، نه تنگ‌تر کردن (بند ۹/۰).
 *
 * ⚠️ کجا گاردِ کلیدواژه‌ای **هنوز** موجه است: بحران. آن‌جا واژه‌ها بی‌ابهام‌اند و
 * عدمِ تقارنِ ضرر کامل است (تصمیمِ صریحِ مالک در همان پیام). برای نامِ کارت و برای
 * عدد و الماس **نه**.
 *
 * `moneyClaimIn` عمداً صادر می‌شود ولی **فقط آزمایشگاه** مصرفش می‌کند: سنجه هیچ‌کس
 * را ریفاند نمی‌کند و همان اندازه‌گیری‌ای است که برنامه‌ی مالک («یه مدت اجرا می‌کنیم
 * و هی بهبود می‌دهیم») بدونش کور است. */

/** شرطِ پذیرشِ نسلِ پاکت. **تنها** مسیرِ retryِ زنجیره همین است: پاکتِ خرابِ JSON.
 *  کمبودِ پیشنهاد یا حرفِ خطر عمداً این‌جا **نیست**: ردِ آن‌ها در این نقطه یعنی رفتن به
 *  جمنای/دیپ‌سیک (که پیشنهاد را بدتر رعایت می‌کنند) و در بدترین حالت ریفاند. جایشان
 *  **یک** تعمیرِ هدف‌دار بعد از پذیرش است (`chatFixNeeds`). */
export const chatOutOk = (out) => !!parseChatOut(out);

/* ═══ 🧩 سیستم‌پرامپتِ کاملِ گفتگو (تک‌منبعِ ربات و آزمایشگاه) ═══
 *
 * [پرامپتِ ثابت] + [کانتکستِ همین فال] + [یادآوریِ فرمت]. هر سه per فال ثابت‌اند، پس کلِ
 * بلوک همچنان پیشوندِ **کش‌شونده** است و شرطِ اقتصادیِ v3.84.0 نمی‌شکند.
 *
 * 🐛 چرا یادآوری **بعد از** کانتکست: در دورِ خطِ پایه `luna` بارها به‌جای JSON متنِ
 * خام داد («امروز لازم نیست تکلیف رابطه رو روشن کنی…»)، به‌خصوص در **نوبتِ اول** که هیچ
 * تاریخچه‌ی JSONی برای تقلید ندارد. دستورِ فرمت وسطِ یک پرامپتِ ۶۰۰۰ نویسه‌ای است و بعدش
 * ۳۰۰۰ نویسه متنِ فارسیِ فال می‌آید؛ آخرین چیزی که مدل می‌بیند نثر است و نثر می‌نویسد.
 * نتیجه در پروداکشن: جوابِ اولِ رایگانِ مالک از پله‌ی **فالبک** (جمنای) آمد و پیشنهاد نداشت. */
export function chatSystemPrompt(sysText, ctxBlock, L = null) {
  const tail = L?.prompts?.chatFormatTail || '';
  return tail ? `${sysText}\n\n${ctxBlock}\n\n${tail}` : `${sysText}\n\n${ctxBlock}`;
}

/* ═══ 🎁🛟 تعمیرِ هدف‌دارِ بعد از پذیرش ═══
 *
 * سه کمبود، هر سه با **یک** فراخوانیِ دوباره روی مدلِ اصلی (نه زنجیره‌ی فالبک):
 *   • `thin`   — زیرِ کفِ محتوا (مکانیزمِ v3.100.0، دست‌نخورده)
 *   • `offer`  — پیشنهادِ پایانی ندارد (نه در فیلدش، نه در خطِ آخرِ متن)
 *   • `safety` — حرفِ آسیب/اورژانس بدونِ هیچ نشانه‌ی صریحِ خطر از خودِ کاربر
 * صداکننده `crisisCtx` را از پیام‌های **خودِ کاربر** می‌سازد (`crisisIn`)؛ اگر کاربر
 * صریحاً از خودکشی یا آسیب گفته، حرفِ ایمنی مجاز است و دست نمی‌خورد. */
export function chatFixNeeds(out, { crisisCtx = false } = {}) {
  if (!out) return { offer: false, safety: false };
  const offer = !out.end && !offerLineOk(out.offer) && !offerLineOk(lastLineOf(out.text));
  const safety = !crisisCtx && !!safetyTalkIn(`${out.text || ''}\n${out.offer || ''}`);
  return { offer, safety };
}
/** وزنِ کمبودها — تعمیر فقط وقتی پذیرفته می‌شود که **اکیداً** کمتر باشد.
 * `thin` وزنِ ۲ دارد چون پیامدش پولی است (ریفاندِ الماس)؛ پس جوابِ پُرِ بی‌پیشنهاد از
 * جوابِ توخالیِ پیشنهاددار بهتر شمرده می‌شود، همان رفتارِ v3.100.0. */
export const chatFixScore = (needs, thin) => (needs?.offer ? 1 : 0) + (needs?.safety ? 1 : 0) + (thin ? 2 : 0);

/* ═══ 🧾 متنِ نهاییِ جواب (تک‌منبعِ ربات و آزمایشگاه) ═══
 *
 * ۱) حرفِ خطر، اگر کاربر نشانه‌ی صریحی نداده، جمله‌به‌جمله حذف می‌شود (هم از متن هم از
 *    پیشنهاد). این **آخرین** تور است، بعد از قاعده‌ی پرامپت و بعد از تعمیر.
 * ۲) بدنه از `cleanChatReply` رد می‌شود (پاراگراف‌بندی، خط تیره، نامِ نشتی).
 * ۳) پیشنهاد خطِ آخر می‌شود. اگر مدل **هم** در متن **هم** در فیلد پیشنهاد گذاشته بود،
 *    فقط یکی می‌ماند (مالِ فیلد، چون کنارِ `follow_up` ساخته شده). اگر فیلد خالی بود ولی
 *    خطِ آخرِ متن خودش پیشنهاد بود، همان می‌ماند.
 * ⚠️ نوبتِ `wants_end` پیشنهاد نمی‌گیرد: کاربر خداحافظی کرده و نگه‌داشتنش همان
 * «جمع نکن و خداحافظی نکن» را از جهتِ مخالف نقض می‌کند. */
export function finalizeChatOut(out, { name = '', crisisCtx = false } = {}) {
  let body = String(out?.text || '');
  let offer = String(out?.offer || '');
  let safetyStripped = 0;
  if (!crisisCtx) {
    const b = stripSafetyTalk(body);
    body = b.text; safetyStripped += b.removed;
    if (safetyTalkIn(offer)) { offer = ''; safetyStripped++; }
  }
  const offerOk = !out?.end && offerLineOk(offer);
  if (offerOk) {
    // پیشنهادِ تکراری داخلِ متن ⟵ حذف؛ پیشنهاد فقط یک بار، و همیشه خطِ آخر.
    const ls = body.split('\n');
    let k = ls.length - 1;
    while (k >= 0 && !ls[k].trim()) k--;
    // فقط با الگوی واقعی؛ بدونِ الگو هر خطی «پیشنهاد» حساب می‌شد و خطِ آخرِ جواب می‌پرید.
    if (LANG.offer && k >= 1 && offerLineOk(ls[k])) body = ls.slice(0, k).join('\n');
  }
  let reply = cleanChatReply(body, { name });
  // ⚠️ بدنه‌ای که کلش حرفِ خطر بود و حذف شد، خالی می‌ماند. پیشنهادِ تنها جواب نیست؛
  // `reply` خالی برمی‌گردد و صداکننده آن را مثلِ شکستِ مدل (ریفاند) رفتار می‌کند.
  if (offerOk && reply) {
    const line = cleanChatReply(offer, { name }).replace(/\n+/g, ' ').trim();
    if (line) {
      const room = CHAT_HARD_CHARS - line.length - 1;
      reply = `${cut(reply, Math.max(CHAT_MIN_CHARS, room))}\n${line}`;
    }
  }
  const offerMissing = !out?.end && !offerLineOk(lastLineOf(reply));
  return { reply, offerMissing, safetyStripped };
}


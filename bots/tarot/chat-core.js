/* ═══ سنجه‌ی قلاب ═══
 *
 * قاعده: خطِ آخرِ هر جواب باید به **نامِ یکی از کارت‌های همین فال** یا به یک کلمه‌ی
 * محتواییِ سؤال لنگر بخورد، و تعارفِ بی‌محتوا نباشد.
 *
 * ⚠️ حدِ صداقتِ این سنجه: «لنگر دارد» با «واقعاً کنجکاو می‌کند» یکی نیست. این کفِ
 * کیفیت است و سقفش کارِ روبریکِ سشن است. ولی همین کف دو تستِ ضدِ chatbait را
 * مکانیکی می‌کند: جمله‌ای که بشود بی‌تغییر زیرِ فالِ کاربرِ دیگری گذاشت، رد می‌شود. */
export const CHAT_HOOK_MIN = 30;
export function hookOk(reply, { cardNames = [], questionWords = [] } = {}) {
  const lines = String(reply || '').split('\n').map(s => s.trim()).filter(Boolean);
  if (!lines.length) return { ok: false, why: 'empty' };
  const last = lines[lines.length - 1];
  const nl = norm(last);
  for (const p of LANG.chatbait) { const n = norm(p); if (n && nl.includes(n)) return { ok: false, why: 'chatbait', hit: p }; }
  if (last.length < CHAT_HOOK_MIN) return { ok: false, why: 'short' };
  const anchors = [...cardNames, ...questionWords].map(norm).filter(w => w.length >= 3);
  if (!anchors.some(w => nl.includes(w))) return { ok: false, why: 'noanchor' };
  return { ok: true, why: '' };
}

/** کلماتِ محتواییِ یک سؤال (برای سنجه‌ی لنگر). حروفِ ربط و اضافه‌ی کوتاه می‌افتند. */
export function questionWordsOf(...texts) {
  const out = new Set();
  for (const t of texts) {
    for (const w of norm(t).split(' ')) if (w.length >= 4) out.add(w);
  }
  return [...out];
}

/* ═══ پاکسازیِ خروجی ═══
 * سه چیز، همه **قطعی و بدونِ مدل**: خط تیره‌ی بلند (بند ۱۰ ریشه)، برچسبی که مدل
 * خودسرانه جلوی جواب می‌گذارد، و نامِ کاربر اگر نشت کرد.
 * ⚠️ هیچ ویرایشِ معناییِ خودکاری انجام نمی‌شود: `repair.js` این‌جا صدا زده نمی‌شود
 * (یک فراخوانیِ ~۱٫۱ ثانیه‌ای برای متنی که یک‌دهمِ فال است صرف نمی‌کند). */
const LABEL_RE = /^\s*(?:تاروت[‌ ]?خوان|فالگیر|جواب|پاسخ|assistant)\s*[:：-]\s*/i;

/* ═══ پاراگراف‌بندیِ قطعی ═══
 *
 * 🐛 ایرادِ واقعیِ دورهای آزمایشگاه: ~۴۰٪ گفتگوها جوابی داشتند که **یک بلوکِ فشرده**
 * بود؛ نه بد، ولی خواندنش روی موبایل سخت. سه واریانتِ پرامپت که صریح می‌گفتند «خط
 * جدا کن» هر سه **بدتر** شدند (۰/۶ گفتگو داخلِ هدف در برابرِ ۱۱/۱۸ بدونشان)، چون
 * همان دستور طولِ جواب را هم باد می‌کرد. پس این کارِ پرامپت نیست، کارِ کد است
 * (بند ۹/۰ ریشه: وقتی داری لایه‌ی دومِ وصله را می‌نویسی بایست).
 *
 * سه گاردِ عمدی، هر سه از سنجشِ ۱۲۰ نوبتِ واقعیِ جمع‌شده آمدند نه از شهود:
 * ۱) اگر مدل **خودش** خط جدا کرده باشد، اصلاً دست نمی‌زنیم.
 * ۲) جوابِ کوتاه (زیرِ `minChars`) یک‌تکه می‌ماند؛ تکه‌کردنِ دو جمله‌ی کوتاه متن را
 *    بریده‌بریده می‌کند نه خوانا.
 * ۳) جداکننده فقط `.؟!` است. `؛` عمداً **بیرون** است: با آن ۹۳ خط به نیم‌جمله‌ای
 *    ختم می‌شد که با نقطه‌ویرگول تمام می‌شود، یعنی یک خطِ ناتمام.
 * جمله‌های اضافه‌ی بعد از سقف به خطِ آخر می‌چسبند تا هیچ جمله‌ای حذف نشود.
 * سنجیده روی همان ۱۲۰ نوبت: ۵۳٪ ⟵ ۹۹٪ داخلِ هدف، و **هیچ جوابِ سالمی خراب نشد**. */
export const CHAT_SPLIT_MIN_CHARS = 150;
export const CHAT_SPLIT_MAX_LINES = 6;
export function splitChatLines(text, { max = CHAT_SPLIT_MAX_LINES, minChars = CHAT_SPLIT_MIN_CHARS } = {}) {
  const t = String(text || '');
  if (/\n/.test(t)) return t;
  if (t.length < minChars) return t;
  const parts = t.split(/(?<=[.؟!])\s+(?=\S)/g).filter(Boolean);
  if (parts.length < 2) return t;
  if (parts.length <= max) return parts.join('\n');
  const out = parts.slice(0, max - 1);
  out.push(parts.slice(max - 1).join(' '));
  return out.join('\n');
}

export function cleanChatReply(text, { name = '' } = {}) {
  let t = noDash(String(text || '')).trim();
  t = t.replace(LABEL_RE, '').trim();
  if (name && name.length >= 2) {
    // فقط نامِ نشتی‌شده حذف می‌شود، نه هر کلمه‌ی مشابه: مرزِ واژه لازم است.
    // ⚠️ فشرده‌سازیِ فاصله عمداً `[^\S\n]` است نه `\s`: `\s` خطِ جدید را هم می‌خورد،
    // پس جوابی که مدل خودش چندخطی نوشته بود با نشتِ نام یک‌تکه می‌شد — بی‌صدا، و
    // فقط برای کاربرانی که نامشان در متن آمده بود.
    const esc = name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    t = t.replace(new RegExp(`(^|[\\s،,:!؟?])${esc}([\\s،,:!؟?]|$)`, 'g'), '$1$2')
      .replace(/[^\S\n]{2,}/g, ' ')
      .replace(/[^\S\n]+\n/g, '\n')
      .trim();
  }
  return cut(splitChatLines(t), CHAT_HARD_CHARS);
}


`EVIDENCE-BASED RESUME PRINCIPLES (apply strictly):

ATS & STRUCTURE
- Single-column. Use exact standard section headings ("Professional Summary", "Skills", "Professional Experience", "Education", "Certifications"). Never creative headings like "My Journey".
- No tables, columns, or text boxes (they break ATS parsing and downstream rendering).
- Reverse-chronological (newest first). Avoid skills-only/functional layouts — recruiters distrust them.

KEYWORD TAILORING — the single biggest lever
- Mirror the TARGET JOB's exact terminology and hard skills verbatim (write "Project Manager", "Python" — not "managed projects", "experienced in coding"). Lexical mismatch silently drops ATS ranking.
- Naturally cover ~70-80% of the job's key terms/required skills that the candidate genuinely has.
- Front-load: put the most job-relevant skills, bullets, and roles first (recruiters scan ~7s in an F-pattern). Per role, keep the 3-6 achievements that best match the job's stated needs; de-emphasize or drop unrelated ones.

PROFESSIONAL SUMMARY (not an Objective)
- 2-3 lines (~40-60 words): a value proposition = top competencies + biggest quantified achievements aligned to THIS job. No first-person wishes. Use an Objective only for new grads or a radical career change.

EXPERIENCE BULLETS — Google's XYZ formula
- "Accomplished [X result], measured by [Y metric], by doing [Z action/skill]."
- Start every bullet with a strong action verb (Led, Built, Optimized, Increased, Reduced, Launched, Designed). Never "Responsible for".
- Quantify with real numbers from the data; prefer precise figures (19% beats a round 20%). If no exact metric exists, give scale instead (e.g., "team of 12", "across 3 markets"). Impact/results over duties.

QUALITY & TRUST SIGNALS
- Flawless spelling/grammar; consistent tense (past tense for past roles) and consistent date formatting.
- Keep job titles, companies, and dates truthful and consistent with the profile.
- If a LinkedIn/portfolio/GitHub URL exists in the data, include it in the header.
- Do NOT add "References available upon request" or any filler.

LENGTH
- One page for <3-5 years of experience or a radical career change; up to two pages for experienced candidates — include enough quantified evidence rather than over-compressing.

ABSOLUTE HONESTY: Use ONLY the candidate's real, provided data. Never invent employers, titles, dates, metrics, or skills.`;

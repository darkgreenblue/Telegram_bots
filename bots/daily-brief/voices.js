// یک واحد ببر بالا تا نمونه‌های کهنه دوباره ساخته شوند. بدونِ این، تغییرِ متن بی‌اثر می‌ماند
// چون فایل‌های قدیمی همچنان از کش سرو می‌شوند.
export const SAMPLE_VERSION = 1;

export const voiceById = (id) => VOICES.find((v) => v.id === id) || null;
export const voiceLabel = (id) => {
  const v = voiceById(id);
  return v ? `${v.name} (${v.tone})` : 'پیش‌فرض';
};


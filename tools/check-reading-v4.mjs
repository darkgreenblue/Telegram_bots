#!/usr/bin/env node
// چکِ ساختارِ خوانشِ v4 (bots/tarot/STYLE.md).
//
// این ساختار از تقاطعِ دو چیز درآمده: تحلیلِ خوانش‌های واقعیِ یک تاروت‌خوانِ انسان، و دو
// تحقیقِ مستقل درباره‌ی اینکه چه چیزی در خروجی باعث بازگشتِ کاربر می‌شود. هرچه در **هر
// دو** بوده وزنِ بالا گرفته و اینجا قفل شده، تا در بازنویسی‌های بعدی بی‌صدا از بین نرود.
import fs from 'node:fs';

const SRC = fs.readFileSync(new URL('../bots/tarot/index.js', import.meta.url), 'utf8');
const LOC = fs.readFileSync(new URL('../bots/tarot/locales/fa.js', import.meta.url), 'utf8');
const V4 = LOC.slice(LOC.indexOf('readerSystemV4'), LOC.indexOf('readerSystem: (spread)'));

let pass = 0; const errs = [];
const ok = (c, m) => { if (c) { pass++; console.log(`  ✅ ${m}`); } else { errs.push(m); console.log(`  ❌ ${m}`); } };

console.log('▶ دامنه و رول‌بک (بند ۲ج-۲ ریشه)');
{
  ok(/const READING_V4 = true;/.test(SRC), 'پرچمِ اصلی روشن است');
  ok(/const READING_V4_ADMIN_ONLY = true;/.test(SRC), 'هنوز فقط ادمین (باز کردن = یک PR جدا)');
  ok(/const v4For = \(uid\) => READING_V4 && \(!READING_V4_ADMIN_ONLY \|\| isAdmin\(uid\)\)/.test(SRC),
    'helper هر دو پرچم را با هم چک می‌کند');
  const raw = [...SRC.split('\n').filter(l => !/^\s*\/\//.test(l)).join('\n')
    .matchAll(/\bREADING_V4\b(?!_ADMIN_ONLY)/g)].length;
  ok(raw === 2, `READING_V4 فقط در تعریف و داخلِ v4For استفاده شده (${raw} مورد)`);
}

console.log('\n▶ سرخط: قانونِ «بله‌ی گران»');
{
  // منطقِ خالص واقعاً اجرا می‌شود، نه فقط وجود داشته باشد
  const V = fs.readFileSync(new URL('../bots/tarot/verdict.js', import.meta.url), 'utf8');
  ok(/export function headlineOk/.test(V), 'اعتبارسنجِ سرخط در ماژولِ خالصِ verdict.js است');
  ok(/headlineOk\(obj\.headline\)/.test(SRC), 'سرخط قبل از پذیرش اعتبارسنجی می‌شود');
  ok(/if \(!headlineOk\(obj\.headline\)\) \{ fallback = obj; return false; \}/.test(SRC),
    'سرخطِ بد باعث retry می‌شود ولی خوانشِ سالم را دور نمی‌ریزد (ضدِ ریفاند)');
  // فرمول در خودِ پرامپت
  ok(/\[جهت\] \+ \[قیدِ احتمال\] \+ «اما\/ولی» \+ \[بهای مشخص\]/.test(V4),
    'فرمولِ سرخط صریح در پرامپت آمده');
  ok(/نهِ خشک و بی‌راه‌حل|هرگز نهِ خشک/.test(V4), 'نهِ بی‌راه‌حل ممنوع است');
  ok(/خوش‌بینیِ توخالی ممنوع|دروغِ شیرین/.test(V4),
    'خوش‌بینیِ کاذب ممنوع است (هر دو تحقیق: sugarcoating اعتماد را می‌خورد)');
}

console.log('\n▶ چهار حرکتِ وزن‌بالا (هم در تحقیق‌ها، هم در خوانشِ واقعی)');
{
  ok(/حسِ ناگفته را نام ببر/.test(V4),
    'نام‌گذاریِ حسِ ناگفته — قوی‌ترین محرکِ بازگشت در هر دو تحقیق');
  ok(/الگوی بین‌کارتی را قبل از تک‌تکِ کارت‌ها/.test(V4),
    'الگوی بین‌کارتی قبل از کارت‌به‌کارت (تحقیق: «سنتز» چیزی است که حرفه‌ای را از آماتور جدا می‌کند)');
  ok(/تصویرِ روی کارت را توصیف کن/.test(V4),
    'توصیفِ تصویرِ کارت (تحقیق: فرض نکن مخاطب معنی کارت‌ها را می‌داند)');
  ok(/کارتِ درباری را به یک آدمِ واقعی/.test(V4), 'کارتِ درباری به آدمِ واقعی ترجمه می‌شود');
  ok(/اگر کارتِ بدی که انتظارش می‌رفت \*\*نیامده\*\*/.test(V4),
    'فضای خالی: کارتی که نیامده هم گفته می‌شود');
}

console.log('\n▶ چیزهایی که عمداً **رد** شدند (تناقضِ تحقیق با نمونه یا با تصمیمِ مالک)');
{
  // تحقیق دوم واژگانِ «کائنات/شهود» را پیشنهاد می‌دهد؛ نمونه‌ها هرگز از آن استفاده
  // نمی‌کنند و قاعده‌ی «هر جمله باید جهت داشته باشد» آن را رد می‌کند.
  ok(/«کائنات»/.test(V4) && /ممنوع/.test(V4), '«کائنات» و «به شهودت اعتماد کن» ممنوع مانده‌اند');
  // تحقیق دوم می‌گوید از جوابِ بله/خیر طفره برو؛ خودش هم می‌گوید طفره‌رفتن بازخوردِ منفی
  // می‌گیرد. نمونه‌ها جوابِ صریح می‌دهند، پس صراحت برنده است.
  ok(/طفره رفتن بدترین کاری است/.test(V4), 'طفره‌رفتن صریحاً ممنوع است، نه توصیه‌شده');
  // لیستِ قدم عملی در v3.2.0 حذف شد و نمونه‌ها نصیحت را داخلِ جمله می‌آورند
  ok(/همین‌جا داخلِ جمله بیاید نه به‌صورت لیست/.test(V4), 'نصیحت داخلِ متن است، نه لیستِ قدم عملی');
  ok(!/action_items/.test(V4), 'فیلدِ action_items در v4 وجود ندارد');
  // وابستگی‌سازی: خط قرمزِ صریحِ هر دو تحقیق
  ok(/وابسته کند/.test(V4), 'وابسته‌کردنِ مخاطب ممنوع است (خط قرمزِ هر دو تحقیق)');
}

console.log('\n▶ شکلِ خروجی');
{
  ok(/"teaser"/.test(V4) && /جوابِ نهایی را \*\*لو نده\*\*/.test(V4),
    'مرحله‌ی افشا فقط تیزر دارد و جواب را لو نمی‌دهد');
  // تیزر باید واقعاً درباره‌ی **خودِ کارت** باشد: نام + معنی + تصویر. بازخوردِ میدانی:
  // نسلِ اول تیزرها تفسیر بودند نه معرفیِ کارت، و کاربر ابزاری برای رمزگشایی نداشت.
  ok(/نامِ کارت را بیاور/.test(V4), 'تیزر نامِ کارت را می‌آورد');
  ok(/تصویرِ روی کارت\*\*/.test(V4), 'تیزر یک جمله از تصویرِ روی کارت دارد');
  ok(/ابزار بده تا خودش کم‌کم قصه را بچیند/.test(V4), 'هدفِ تیزر: کاربر خودش رمزگشایی کند');
  ok(/v4 \? llm\.cards\[idx\]\?\.teaser : llm\.cards\[idx\]\?\.text/.test(SRC),
    'در افشا تیزر نمایش داده می‌شود، نه تحلیلِ کامل');
  ok(/const askFeedback = !v4 &&/.test(SRC), 'هیچ بازخوردی وسطِ خوانش گرفته نمی‌شود');
  ok(!/confirmation_question/.test(V4), 'سؤالِ تأییدیِ وسطِ خوانش از پرامپتِ v4 حذف شده');
  ok(/if \(llm\.headline\) await ctx\.reply/.test(SRC), 'متنِ نهایی با سرخط شروع می‌شود');
  // ترتیب: سرخط باید قبل از الگو و کارت‌به‌کارت و جمع‌بندی بیاید
  const fin = SRC.slice(SRC.indexOf('async function finishReading('));
  const iH = fin.indexOf('llm.headline'), iP = fin.indexOf('llm.pattern'), iC = fin.indexOf('llm.closing');
  ok(iH > 0 && iP > iH && iC > iP, 'ترتیبِ کد: سرخط → الگو → جمع‌بندی');
  ok(/جایگاه‌ها[\s\S]{0,60}اسمشان را در متن نیاور/.test(V4),
    'نامِ جایگاه به مدل داده می‌شود ولی در متن نمی‌آید');
  ok(/cardLabels: \(n\)/.test(LOC), 'برچسبِ ترتیبیِ کارت‌ها در locale است');
  ok(/'کارت اولت'/.test(LOC) && /'کارت آخرت'/.test(LOC), 'برچسب‌ها مثل خوانشِ واقعی‌اند');
  ok(/بدونِ ایموجی/.test(V4), 'خروجیِ v4 بدونِ ایموجی است (نمونه‌های واقعی هیچ ایموجی ندارند)');
  ok(/بدونِ تیتر و بولد و بولت/.test(V4), 'بدونِ قالب‌بندی');
  ok(!/parse_mode/.test(SRC.slice(SRC.indexOf('if (v4For(uid)) {'), SRC.indexOf('} else {'))),
    'متنِ v4 خام فرستاده می‌شود (نه HTML) — نه escape لازم است نه ریسکِ خرابیِ قالب');
}

console.log('\n▶ درس‌های تستِ میدانیِ ۱۴۰۵/۰۵/۲۶');
{
  // ۱) نشتِ few-shot: جمله‌ی نمونه‌ی «حسِ ناگفته» در ۲ فال از ۳ فال عیناً تکرار شده بود.
  // تحقیق ۱ همین را دلیلِ شماره‌یکِ رهاکردنِ محصولاتِ AI می‌داند: «repetitive, templated».
  ok(/هر بار از صفر و از دلِ همین سؤال ساخته شود/.test(V4),
    'حسِ ناگفته باید هر بار از نو ساخته شود');
  ok(/عیناً به‌کار نبر/.test(V4), 'الگوی کلیشه‌ای صریحاً ممنوع شده');
  ok(!/«انگار ذهنت انقدر روی این که اگر مخالفت کنن چی می‌شه فوکس کرده/.test(V4),
    'جمله‌ی نمونه‌ی قابلِ کپی از پرامپت حذف شده (منبعِ خودِ نشتی)');

  // ۲) لغزشِ ثبت: یک فال «شما/می‌بینید» شد و بقیه «تو». نمونه‌های واقعی ۱۰۰٪ «تو»اند.
  ok(/\*\*همیشه «تو»، هرگز «شما»\.\*\*/.test(V4), 'خطابِ «تو» قفل شده');

  // ۳) حافظه‌ی بین‌جلسه‌ای: رتبه ۲ تحقیق ۱، و نبودش شایع‌ترین دلیلِ رهاکردن. سه فالِ
  // پشت‌سرهم هیچ ارجاعی به هم نداشتند، پس فیلدِ صریح لازم بود نه توصیه‌ی نرم.
  ok(/"callback":/.test(V4), 'فیلدِ صریحِ ارجاع به جلسه‌ی قبل');
  ok(/llm\.callback && `\$\{SECT\.callback\}/.test(SRC), 'ارجاع در خروجی رندر می‌شود');

  // ۴) پنجره‌ی زمانی: رتبه ۳ تحقیق ۱. هیچ‌کدام از سه فال زمان نداشت.
  ok(/بازه‌ی زمانیِ تقریبی بده/.test(V4), 'جمع‌بندی یک بازه‌ی زمانیِ تقریبی می‌دهد');
}

console.log('\n▶ نقشه‌ی راه و کپشنِ ترتیبی');
{
  ok(/flowIntro: \(n\)/.test(LOC), 'پیامِ نقشه‌ی راه در locale است');
  ok(/if \(n\) await ctx\.reply\(L\.reading\.flowIntro\(n\)\);/.test(SRC), 'نقشه‌ی راه فرستاده می‌شود');
  // ترتیب: نقشه‌ی راه باید **قبل از** پیام‌های انتظار بیاید
  const sr = SRC.slice(SRC.indexOf('async function startReveal('));
  ok(sr.indexOf('flowIntro') > 0 && sr.indexOf('flowIntro') < sr.indexOf('waitLLMWithLoading'),
    'نقشه‌ی راه قبل از پیام‌های انتظار می‌آید');
  ok(/revealCaptionV4:/.test(LOC), 'کپشنِ ترتیبیِ v4 وجود دارد');
  ok(/v4For\(uid\)\s*\?\s*L\.reading\.revealCaptionV4/.test(SRC),
    'کپشنِ عکس در v4 برچسبِ ترتیبی می‌گیرد، نه نامِ جایگاه');
}

console.log('\n▶ ایموجیِ بخش‌بندی (از کد، نه از مدل)');
{
  ok(/const SECT = \{/.test(SRC), 'نشانه‌های بخش در یک نقطه‌ی کد تعریف شده‌اند');
  ok(/بدونِ ایموجی/.test(V4), 'مدل همچنان اجازه‌ی ایموجی ندارد (وگرنه سلیقه‌ای می‌پاشد)');
  for (const k of ['headline', 'pattern', 'card', 'absent', 'closing']) {
    ok(new RegExp(`SECT\\.${k}`).test(SRC), `بخشِ ${k} نشانه دارد`);
  }
}

console.log('\n▶ بازخوردِ ۱ تا ۵ در آخرِ کار');
{
  ok(/rateAsk:/.test(LOC) && /از ۱ تا ۵/.test(LOC), 'سؤالِ بازخورد مقیاسِ ۱ تا ۵ دارد');
  ok(/راضی بودی/.test(LOC), 'سؤال **رضایت** را می‌سنجد، نه انطباق با واقعیت');
  ok(/fbr:\$\{n\}:\$\{readingId\}/.test(SRC), 'دکمه‌ها readingId را حمل می‌کنند (بدونِ وابستگی به state)');
  ok(/bot\.action\(\/\^fbr:\(\[1-5\]\):\(\\d\+\)\$\//.test(SRC), 'هندلرِ بازخوردِ عددی ثبت شده');
  ok(/if \(r\.feedback\) return;/.test(SRC), 'ثبتِ یک‌باره (دوبار-تپ دو رویداد نمی‌سازد)');
  ok(/r\.user_id !== uid\) return;/.test(SRC.slice(SRC.indexOf("bot.action(/^fbr:"))),
    'مالکیتِ رکورد چک می‌شود');
  ok(/`rate:\$\{score\}`/.test(SRC),
    'مقدار با پیشوندِ rate: ذخیره می‌شود تا از yes/some/no قدیمی جدا بماند (بند ۲ج/۳)');
  ok(/EVENTS\.FEEDBACK, \{ reading_id: readingId, score, scale: 5 \}/.test(SRC),
    'propهای جدید اضافه شده‌اند، propهای قدیمی عوض نشده‌اند');
}

console.log('\n▶ اندازه‌ی پرامپت');
{
  // پرامپتِ متورم روی Flash هم گران است هم کیفیت را پایین می‌آورد (درسِ v3.1.0).
  // v4 عمداً بزرگ‌تر از v2 است چون سیستمِ کاملی را حمل می‌کند، ولی همچنان سقف دارد.
  ok(V4.length < 7000, `پرامپتِ v4 زیر سقف است (${V4.length} کاراکترِ سورس، سقف ۷۰۰۰)`);
}

console.log(`\n${errs.length ? '❌' : '✅'} نتیجه: ${pass} پاس، ${errs.length} خطا`);
if (errs.length) { errs.forEach(e => console.log(`   - ${e}`)); process.exit(1); }

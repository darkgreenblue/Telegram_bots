export const MAX = CHAT_RUBRIC.reduce((s, r) => s + r.w * 2, 0);

/** نرمال‌سازیِ سبک برای تطبیقِ نقلِ قول: نیم‌فاصله، نویسه‌های عربی، نشانه‌گذاری، فاصله. */
const norm = (s) => String(s || '')
  .replace(/[‌‏‎]/g, '')
  .replace(/[يى]/g, 'ی').replace(/ك/g, 'ک')
  .replace(/[«»"'`.,؛;:!?؟()\[\]]/g, '')
  .replace(/\s+/g, ' ')
  .trim();

/**
 * راستی‌آزماییِ شاهدِ یک ارزیابی.
 *
 * ورودی همان چیزی است که سشن (داور) می‌نویسد:
 *   `{ items: { <id>: { score: 0..2, quote: '…' } }, note?: '…' }`
 * و `text` متنِ **واقعیِ** همان نوبت است.
 *
 * ⚠️ هر نمره‌ی بالای صفر که نقلِ قولش در متن نباشد، **به صفر برمی‌گردد** و شناسه‌اش
 * در `faked` گزارش می‌شود. این مهم‌ترین (و تنها) گاردِ این فایل است.
 */
export function verifyEvidence(parsed, text) {
  const hay = norm(text);
  const items = {}; let got = 0; const faked = [], missing = [];
  for (const r of CHAT_RUBRIC) {
    const raw = parsed?.items?.[r.id] || {};
    if (parsed?.items && !(r.id in parsed.items)) missing.push(r.id);
    let sc = Math.max(0, Math.min(2, Number(raw.score) || 0));
    const q = String(raw.quote || '').trim();
    // نقلِ قولِ کوتاه‌تر از ۸ نویسه ثابت‌کننده‌ی چیزی نیست.
    const proven = q.length >= 8 && hay.includes(norm(q));
    if (sc > 0 && !proven) { faked.push(r.id); sc = 0; }
    items[r.id] = { score: sc, quote: q, proven, w: r.w };
    got += sc * r.w;
  }
  return { items, got, max: MAX, pct: Math.round(got * 100 / MAX), faked, missing,
    note: String(parsed?.note || '').slice(0, 160) };
}

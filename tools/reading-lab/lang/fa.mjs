/** فعل‌های اول‌شخصِ پیشنهاد ⟵ [{kind:'light'|'verb'|'know', forms:[…], pre?}] */
function offerVerbs(offer) {
  const toks = faTokens(offer);
  const out = [];
  toks.forEach((t, i) => {
    if (MODALS.has(t) || NOT_VERB.has(t)) return;
    if (KNOW.has(t)) { out.push({ kind: 'know' }); return; }
    if (LIGHT_OFFER.test(t)) {
      const prev = toks[i - 1] || '';
      out.push({ kind: 'light', pre: FUNC.has(prev) ? '' : prev });
      return;
    }
    const m = t.match(/^(?:ن?می‌?|ب)(.+?)(یم|م)$/);
    if (!m || m[1].length < 1) return;
    const stem = m[1];
    const forms = IRREG[stem] ? [...IRREG[stem]] : [`ب${stem}`, `ب${stem}ی`];
    // «بریم سراغش»: پیشنهادِ اول‌شخصِ جمع را همان شکل هم قبول می‌کند.
    if (m[2] === 'یم') forms.push(`ب${stem}یم`);
    out.push({ kind: 'verb', forms });
  });
  return out;
}
const hasForm = (btnToks, forms) => btnToks.some((b) => forms.some((f) => b.startsWith(f) && CLITIC.test(b.slice(f.length))));
const preMatch = (b, pre) => pre.length >= 3 && b.length >= 3 && (b.startsWith(pre) || pre.startsWith(b));

export function followUpMirror(offer, label) {
  const btn = faTokens(label);
  if (!btn.length) return 'nolabel';
  const verbs = offerVerbs(offer);
  if (!verbs.length) return 'noverb';
  const content = (s) => new Set(faTokens(s).filter((w) => w.length >= 4 && !MODALS.has(w)));
  for (const v of verbs) {
    if (v.kind === 'verb' && hasForm(btn, v.forms)) return '';
    if (v.kind === 'light' && btn.some((b) => LIGHT_BTN.has(b))
      && (!v.pre || btn.some((b) => preMatch(b, v.pre)))) return '';
    if (v.kind === 'know') {
      if (hasForm(btn, KNOW_BTN)) return '';
      // «می‌خوای بدونی X؟» ⟵ خودِ سؤالِ X هم قبولِ همان پیشنهاد است.
      const oc = content(offer);
      if (/[?؟]\s*$/.test(label) && [...content(label)].some((w) => oc.has(w))) return '';
    }
  }
  return META_Q.test(faNorm(label)) ? 'meta-q' : 'mismatch';
}


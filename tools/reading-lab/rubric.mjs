export function judgeUser({ question, cardNames, text }) {
  return [
    `سؤالِ کاربر: ${question || '(بدونِ سؤالِ مشخص)'}`,
    `کارت‌های کشیده‌شده: ${(cardNames || []).join('، ')}`,
    '',
    'متنِ فال:',
    '---',
    text,
    '---',
  ].join('\n');
}

/** نرمال‌سازیِ سبک برای تطبیقِ نقلِ قول: فاصله‌ها و نیم‌فاصله و نویسه‌های عربی/فارسی. */
const norm = (s) => String(s || '')
  .replace(/[‌‏‎]/g, '')
  .replace(/[يى]/g, 'ی').replace(/ك/g, 'ک')
  .replace(/[«»"'`.,؛;:!?()\[\]]/g, '')
  .replace(/\s+/g, ' ')
  .trim();

/**
 * نمره‌ی داور را **راستی‌آزمایی** می‌کند: هر نقلِ قولی که واقعاً در متن نباشد، توهمِ
 * داور است و آن معیار به صفر برمی‌گردد.
 *
 * ⚠️ این مهم‌ترین گاردِ این فایل است. بدونش، داور می‌تواند با اختراعِ نقلِ قول به هر
 * متنی نمره‌ی بالا بدهد و ما دوباره روی یک ابزارِ خراب تصمیم بگیریم — دقیقاً همان
 * درسی که یازده باگِ این پروژه ثبت کرده‌اند.
 */
export function scoreOf(parsed, text) {
  const hay = norm(text);
  const items = {}; let got = 0; const faked = [];
  for (const r of RUBRIC) {
    const raw = parsed?.items?.[r.id] || {};
    let sc = Math.max(0, Math.min(2, Number(raw.score) || 0));
    const q = String(raw.quote || '').trim();
    // نقلِ قولِ کوتاه‌تر از ۸ نویسه ثابت‌کننده‌ی چیزی نیست
    const proven = q.length >= 8 && hay.includes(norm(q));
    if (sc > 0 && !proven) { faked.push(r.id); sc = 0; }
    items[r.id] = { score: sc, quote: q, proven, w: r.w };
    got += sc * r.w;
  }
  return { items, got, max: MAX, pct: Math.round(got * 100 / MAX), faked,
           weakest: parsed?.weakest || '', note: String(parsed?.note || '').slice(0, 120) };
}

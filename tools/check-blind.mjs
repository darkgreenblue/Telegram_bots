#!/usr/bin/env node
/* گاردِ ابزارِ نمره‌دهیِ کور (`tools/reading-lab/blind.mjs`).
 *
 * چرا این گارد **رفتاری** است و نه رجکسی: کلِ ارزشِ آن ابزار یک ادعای منفی است
 * («هیچ ردی از بازو در متنِ کور نیست»). و طبقِ بند ۶ب-۲ ریشه، یک ادعای منفیِ سبز دو
 * معنیِ کاملاً متفاوت دارد: «چیزی نیست» یا «چیزی را که هست نمی‌بینم». پس هر ادعای
 * منفی این‌جا یک **کنترلِ مثبت** کنارش دارد که ثابت می‌کند همان ادعا روی یک ورودیِ
 * عمداً آلوده **قرمز** می‌شود. بدونِ آن، یک پارسرِ همیشه-خالی همه‌ی ادعاهای منفی را
 * پاس می‌کرد.
 */
import { parseTranscripts, splitBlind, refTextOf } from './reading-lab/blind.mjs';

let pass = 0, fail = 0;
const ok = (c, m) => { if (c) { pass++; console.log(`✅ ${m}`); } else { fail++; console.log(`❌ ${m}`); } };

const ARM_A = 'openai/gpt-5.6-luna';
const ARM_B = 'deepseek/deepseek-v4-flash-0731:free';

const block = (arm, persona, step, spread, q, cards, body) =>
  [`▓ ${arm} | ${persona}.${step} | ${spread}`, `؟ ${q}`, `🃏 ${cards}`, body].join('\n');

const LOG = [
  '═'.repeat(72),
  '📄 رونوشتِ کاملِ فال‌ها (برای ارزیابیِ دستیِ کیفیت)',
  '═'.repeat(72),
  '',
  block(ARM_A, 'P1', 1, 'سه کارتِ شغلی', 'کارم رو عوض کنم؟', 'برجِ آسمان، سه شمشیر', 'سرخطِ الف\nمتنِ بدنه‌ی الف\nجمع‌بندیِ الف'),
  '',
  block(ARM_B, 'P1', 1, 'سه کارتِ شغلی', 'کارم رو عوض کنم؟', 'برجِ آسمان، سه شمشیر', 'سرخطِ ب\nمتنِ بدنه‌ی ب\nجمع‌بندیِ ب'),
  '',
  block(ARM_A, 'P2', 3, 'پنج کارتِ پول', 'وام بگیرم؟', 'شاهِ سکه، دو سکه', 'سرخطِ پ\nمتنِ بدنه‌ی پ\nجمع‌بندیِ پ'),
  '',
  block(ARM_B, 'P2', 3, 'پنج کارتِ پول', 'وام بگیرم؟', 'شاهِ سکه، دو سکه', 'سرخطِ ت\nمتنِ بدنه‌ی ت\nجمع‌بندیِ ت'),
].join('\n');

/* ═══ ۱) پارس روی هر دو شکلِ واقعیِ منبع ═══ */
const rows = parseTranscripts(LOG);
ok(rows.length === 4, `چهار فال از لاگِ محلی پارس شد (${rows.length})`);
ok(rows.filter(r => r.arm === ARM_A).length === 2 && rows.filter(r => r.arm === ARM_B).length === 2,
  'بازوی هر فال درست خوانده شد');
ok(rows[0].question === 'کارم رو عوض کنم؟' && rows[0].cards.includes('برجِ آسمان'),
  'سؤال و کارت‌ها به فالِ خودشان چسبیده‌اند');

// لاگِ گیت‌هاب مهرِ زمانِ ISO دارد؛ هر دو منبع باید کار کنند
const STAMPED = LOG.split('\n').map((l, i) =>
  `2026-09-19T09:3${i % 10}:0${i % 10}.1234567Z ${l}`).join('\n');
const rowsTs = parseTranscripts(STAMPED);
ok(rowsTs.length === 4, `همان لاگ با مهرِ زمانِ گیت‌هاب هم ۴ فال داد (${rowsTs.length})`);
ok(rowsTs[0]?.arm === ARM_A && rowsTs[0]?.question === rows[0].question,
  'مهرِ زمان به بازو و سؤال نچسبیده');

/* کنترلِ مثبت: هدرِ عوض‌شده باید **صفر** بدهد، نه اینکه بی‌صدا چیزِ اشتباه بسازد.
 * بدونِ این، تغییرِ فردایِ فرمتِ رونوشت یک نمره‌دهیِ روی هیچ می‌ساخت. */
ok(parseTranscripts(LOG.replace(/^▓ /gm, '# ')).length === 0,
  'کنترلِ مثبت: هدرِ ناشناخته ⟵ صفر فال (نه پارسِ خاموش)');

/* ═══ ۲) ادعای مرکزی: خروجیِ کور هیچ ردی از بازو ندارد ═══ */
const { blind, key } = splitBlind(rows, 'seed-1');
const leaks = [ARM_A, ARM_B, 'openai', 'deepseek', 'luna', 'flash', ':free']
  .filter(s => blind.toLowerCase().includes(s.toLowerCase()));
ok(leaks.length === 0, `متنِ کور هیچ نامِ بازو ندارد${leaks.length ? ` (نشت: ${leaks.join(', ')})` : ''}`);

/* کنترلِ مثبت برای همان ادعا: عینِ همان بررسی روی یک رندرِ **عمداً برچسب‌دار** باید
 * قرمز شود. اگر نشود، یعنی فهرستِ نشت اشتباه است و ادعای بالا بی‌معنا. */
{
  const dirty = rows.map(r => `## X\n- بازو: ${r.arm}\n${r.body.join('\n')}`).join('\n');
  const found = ['openai', 'deepseek'].filter(s => dirty.toLowerCase().includes(s));
  ok(found.length === 2, 'کنترلِ مثبت: همان بررسی روی متنِ برچسب‌دار نشت را می‌گیرد');
}

/* شناسه‌ی سناریو هم عمداً بیرون است (وگرنه «سه بارِ P1.1» به حدسِ ترتیبِ بازوها
 * وسوسه می‌کند)، با کنترلِ مثبتِ خودش. */
ok(!/\bP1\.1\b/.test(blind) && !/\bP2\.3\b/.test(blind),
  'شناسه‌ی سناریو در متنِ کور نیست');
ok(/\bP1\.1\b/.test('پیش‌نویسِ آلوده: P1.1'),
  'کنترلِ مثبت: همان الگو شناسه‌ی سناریو را می‌گیرد');

/* ═══ ۳) چیزهایی که باید **بمانند** ═══ */
// بدونِ کارت‌ها معیارِ `card_anchor` و بدونِ سؤال معیارِ `direct` قابلِ داوری نیستند.
ok(blind.includes('برجِ آسمان، سه شمشیر') && blind.includes('شاهِ سکه، دو سکه'),
  'فهرستِ کارت‌ها در متنِ کور مانده (لازمِ معیارِ لنگرِ کارت)');
ok(blind.includes('کارم رو عوض کنم؟') && blind.includes('وام بگیرم؟'),
  'سؤالِ کاربر در متنِ کور مانده (لازمِ معیارِ جوابِ صریح)');
ok(rows.every(r => blind.includes(r.body[0])), 'متنِ هر چهار فال کامل منتقل شد');

/* ═══ ۴) کلید: round-trip و یکتایی ═══ */
const ids = Object.keys(key);
ok(ids.length === 4, `کلید برای هر چهار فال ردیف دارد (${ids.length})`);
ok(new Set(ids).size === ids.length, 'شناسه‌ها یکتا هستند');
ok(ids.every(id => new RegExp(`^## ${id}$`, 'm').test(blind)),
  'هر شناسه‌ی کلید در متنِ کور بخشِ خودش را دارد');
{
  const back = ids.map(id => key[id].arm).sort();
  ok(JSON.stringify(back) === JSON.stringify(rows.map(r => r.arm).sort()),
    'کلید همان توزیعِ بازوها را برمی‌گرداند (round-trip)');
  ok(ids.every(id => key[id].persona && key[id].step && key[id].spread),
    'کلید سناریوی هر شناسه را هم نگه داشته (لازمِ تفاضلِ جفت‌شده)');
}

/* ═══ ۵) شافل: هم واقعاً بُر می‌زند، هم قطعی است ═══ */
{
  const many = Array.from({ length: 12 }, (_, i) =>
    ({ arm: i % 2 ? ARM_A : ARM_B, persona: `P${i}`, step: 1, rep: 1, spread: 'س',
       question: `سؤالِ ${i}`, cards: 'کارت', body: [`متنِ ${i}`] }));
  const order = (o) => Object.values(o.key).map(k => k.persona).join(',');
  const a = splitBlind(many, 'x'), b = splitBlind(many, 'x'), c = splitBlind(many, 'y');
  ok(order(a) === order(b), 'با seedِ یکسان ترتیب عیناً بازتولید می‌شود');
  ok(order(a) !== order(c), 'با seedِ متفاوت ترتیب عوض می‌شود');
  ok(order(a) !== many.map(r => r.persona).join(','), 'ترتیبِ خروجی با ترتیبِ ورودی یکی نیست');
  /* و مهم‌تر: بازوها نباید **متناوب** بمانند، وگرنه داور از الگوی یک‌درمیانِ ورودی
   * می‌تواند بازو را حدس بزند و کوری فقط اسمی است. */
  const armSeq = Object.values(a.key).map(k => k.arm === ARM_A ? 'A' : 'B').join('');
  ok(!/^(AB)+$|^(BA)+$/.test(armSeq), `الگوی متناوبِ بازوها شکسته شد (${armSeq})`);
}

/* ═══ ۶) برچسبِ مجموعه: شناسه‌ی سناریو بینِ مجموعه‌ها یکتا **نیست** ═══
 *
 * 🐛 باگی که قبل از اولین استفاده گرفته شد: `P1.1` در هر سه مجموعه‌ی فارسی هست، با
 * کارت و سؤالِ کاملاً متفاوت. اگر کلید فقط `persona.step` نگه دارد، تفاضلِ جفت‌شده سه
 * سناریوی بی‌ربط را یکی می‌شمارد و دو سومِ دیتا **بی‌صدا** دور می‌ریزد. */
{
  const mk = (tag, persona, step, body) =>
    ({ arm: ARM_A, persona, step, rep: 1, spread: 'س', set: tag,
       question: `سؤالِ ${tag}`, cards: 'کارت', body: [body] });
  const mixed = [
    mk('alef', 'P1', 1, 'متنِ الف'), { ...mk('alef', 'P1', 1, 'متنِ الف۲'), arm: ARM_B },
    mk('b', 'P1', 1, 'متنِ ب'),      { ...mk('b', 'P1', 1, 'متنِ ب۲'), arm: ARM_B },
    mk('c', 'P1', 1, 'متنِ ج'),      { ...mk('c', 'P1', 1, 'متنِ ج۲'), arm: ARM_B },
  ];
  const { key } = splitBlind(mixed, 'mix');
  const scens = new Set(Object.values(key).map(k => k.scen));
  ok(scens.size === 3, `سه مجموعه سه سناریوی متمایز دادند، نه یکی (${scens.size})`);
  ok([...scens].every(x => /^(alef|b|c)\/P1\.1$/.test(x)),
    `شناسه‌ی سناریو برچسبِ مجموعه را حمل می‌کند (${[...scens].sort().join(' , ')})`);
  ok(Object.values(key).every(k => k.set), 'برچسبِ مجموعه در هر ردیفِ کلید هست');
  // کنترلِ مثبت: بازسازیِ بدونِ برچسب همان سه تا را به **یک** سناریو می‌چسباند
  const naive = new Set(Object.values(key).map(k => `${k.persona}.${k.step}`));
  ok(naive.size === 1,
    'کنترلِ مثبت: بازسازیِ بی‌برچسب هر سه مجموعه را یک سناریو می‌بیند (باگی که رفع شد)');
}

/* ═══ ۷) راستی‌آزماییِ شاهد نباید سرِ بلوک را متنِ فال بشمارد ═══
 *
 * `scoreOf` نمره‌ی بی‌شاهد را صفر می‌کند و همین کلِ ارزشش است. ولی اگر متنِ مرجع شاملِ
 * **سؤالِ کاربر** باشد، نقلِ قولی از سؤال هم «اثبات‌شده» می‌شود، در حالی که معیارها
 * دربارهٔ چیزی‌اند که مدل **نوشته**. این ادعا همان برشی را می‌سنجد که حالتِ `score`
 * می‌زند، با کنترلِ مثبتی که ثابت می‌کند بدونِ برش نشت واقعی است. */
{
  const rows2 = [{ arm: ARM_A, persona: 'P9', step: 1, rep: 1, spread: 'سه کارتی', set: 't',
                   question: 'یک عبارتِ یکتا در سؤال', cards: 'برجِ آسمان',
                   body: ['یک عبارتِ یکتا در متنِ فال'] }];
  const { blind: b2 } = splitBlind(rows2, 'q');
  const chunk = b2.split(/^## /m)[1];
  // ⚠️ **خودِ تابعِ ابزار** صدا زده می‌شود، نه بازسازیِ محلیِ برش: وگرنه این ادعا آینه‌ی
  // خودش است و حذفِ برش در `score` را نمی‌گیرد (همان جهشی که اول سبز ماند).
  const refText = refTextOf(chunk);
  ok(refText.includes('یک عبارتِ یکتا در متنِ فال'), 'متنِ مرجع خودِ فال را دارد');
  ok(!refText.includes('یک عبارتِ یکتا در سؤال'),
    'متنِ مرجع سؤالِ کاربر را ندارد (نقلِ قول از سؤال شاهد نمی‌شود)');
  ok(chunk.includes('یک عبارتِ یکتا در سؤال'),
    'کنترلِ مثبت: سؤال در بلوکِ کور هست، پس برش واقعاً کاری می‌کند');
}

/* ═══ ۸) دنباله‌ی لاگ نباید وارد بدنه‌ی فالِ آخر شود ═══
 *
 * 🐛 باگی که **فقط دادهٔ واقعی** لو داد و فیکسچرِ دست‌سازِ بالا سبز بود: لاگِ واقعی بعد
 * از آخرین رونوشت، خلاصه‌ی per بازوی خودِ ورک‌فلو را چاپ می‌کند (`── openai/…`). بدنه‌ی
 * فالِ آخر تا انتها بلعیده می‌شد، پس نامِ **هر سه بازو** داخلِ متنِ کور می‌نشست. یعنی
 * درسِ ۹/۰ب یک بار دیگر: فیکسچر همان چیزی را می‌سنجد که نویسنده‌اش **فکر می‌کند** رخ
 * می‌دهد. این فیکسچر عمداً **شکلِ واقعیِ** دنباله‌ی لاگ را دارد. */
{
  const REAL = [
    '════════════════════════════════════════',
    '📄 رونوشتِ کاملِ فال‌ها (برای ارزیابیِ دستیِ کیفیت)',
    '════════════════════════════════════════',
    '',
    block(ARM_A, 'Z1', 1, 'سه کارتی', 'سؤالِ یک؟', 'آس شمشیر، دو جام',
      '🔮 سرخطِ یک\n🧩 الگوی یک\n🕯️ جمع‌بندیِ یک'),
    '',
    block(ARM_B, 'Z1', 1, 'سه کارتی', 'سؤالِ یک؟', 'آس شمشیر، دو جام',
      '🔮 سرخطِ دو\n🧩 الگوی دو\n🕯️ جمع‌بندیِ دو'),
    '',
    '💾 خروجیِ خام: reading-lab-out.json',
    'Node 20 is being deprecated. This workflow is running with Node 24 by default.',
    '##[group]Run actions/upload-artifact@v4',
    '  name: reading-lab-fa',
    '##[endgroup]',
    '═══ خلاصه ═══',
    '',
    `── ${ARM_A}`,
    '   فال: 9 | ایرادناک: 0',
    `── ${ARM_B}`,
    '   فال: 9 | ایرادناک: 2',
  ].join('\n');

  // کنترلِ مثبت: خودِ فیکسچر واقعاً نامِ بازوها را در دنباله دارد، وگرنه ادعای زیر پوچ است
  ok(REAL.split('📄')[1].includes(ARM_A) && REAL.includes(`── ${ARM_B}`),
    'کنترلِ مثبت: دنباله‌ی فیکسچر نامِ بازوها را دارد (پس مرزِ پایانی کار دارد)');

  const rr = parseTranscripts(REAL);
  ok(rr.length === 2, `دو فال پارس شد، نه بیشتر و نه کمتر (${rr.length})`);
  const lastBody = (rr[rr.length - 1] || { body: [] }).body.join('\n');
  ok(lastBody.includes('جمع‌بندیِ دو'), 'بدنه‌ی فالِ آخر جمع‌بندیِ خودش را دارد');
  ok(!/openai|deepseek|##\[|💾|خلاصه/.test(lastBody),
    'بدنه‌ی فالِ آخر هیچ تکه‌ای از دنباله‌ی لاگ را ندارد');

  const { blind: b3 } = splitBlind(rr, 'real');
  ok(!/openai|deepseek|luna/i.test(b3), 'متنِ کورِ ساخته‌شده از لاگِ واقعی‌شکل نشت ندارد');

  /* و مارکرِ **شروع** هم بار می‌کشد، نه فقط مرزهای پایانی: لاگِ واقعی قبل از بلوکِ
   * رونوشت، سرِ هر فال را به شکلِ `── B1.1 «چیدمان» …` چاپ می‌کند، و `── ` یکی از
   * مرزهای پایانی است. بدونِ بریدن از مارکر، پارس روی همان خطِ اول متوقف می‌شود و
   * **صفر** فال می‌دهد (روی لاگِ واقعیِ ۲۷فالی سنجیده شد). این ادعا همان را قفل می‌کند. */
  const WITH_INLINE = [
    '── Z1.1 «سه کارتی» (3 کارت) قدمِ اول',
    '   سؤال: سؤالِ یک؟',
    '   📏 1200 کاراکتر',
    REAL,
  ].join('\n');
  const rr2 = parseTranscripts(WITH_INLINE);
  ok(rr2.length === 2,
    `بلوکِ درون‌خطیِ قبل از مارکر پارس را متوقف نمی‌کند (${rr2.length} فال، انتظار ۲)`);
}

/* ═══ ۹) self-checkِ خودِ ابزار: خروجیِ بی‌اعتبار باید **بلند** شکست بخورد ═══
 * چرا لازم است: همان نشت روی فیکسچرِ دست‌ساز سبز بود. ابزاری که می‌تواند فایلِ
 * بی‌اعتبار بسازد نباید ساکت بماند، چون داور فایل را «درست» فرض می‌کند. */
{
  const poisoned = [{ arm: ARM_A, persona: 'Z2', step: 1, rep: 1, spread: 'س', set: 't',
    question: 'سؤال', cards: 'کارت',
    body: ['متنِ فال', `── ${ARM_B}`, '   فال: 9'] }];
  let threw = '';
  try { splitBlind(poisoned, 'p'); } catch (e) { threw = e.message; }
  ok(threw.includes('نشتِ نامِ بازو'),
    `ابزار روی نشتِ اسلاگِ یک بازوی **دیگر** صریح خطا می‌دهد (${threw ? 'خطا داد' : 'ساکت ماند'})`);
  /* و مسیرِ دومِ تشخیص: نامِ بازوی **خودِ** همان اجرا. دو مسیر عمداً جدا سنجیده می‌شوند،
   * چون نسخه‌ی اولِ self-check فقط این یکی را داشت و آن یکی را بی‌صدا رد می‌کرد. */
  let threwOwn = '';
  try {
    splitBlind([{ ...poisoned[0], body: ['متنِ فال', `اجرا شده روی ${ARM_A}`] }], 'p2');
  } catch (e) { threwOwn = e.message; }
  ok(threwOwn.includes('نشتِ نامِ بازو'),
    `و روی نشتِ نامِ بازوی خودش هم (${threwOwn ? 'خطا داد' : 'ساکت ماند'})`);
  // و کنترلِ مثبتِ معکوس: بدنه‌ی سالم نباید خطا بدهد، وگرنه self-check همه‌چیز را می‌بندد
  let clean = true;
  try { splitBlind([{ ...poisoned[0], body: ['متنِ فالِ سالم'] }], 'p'); } catch { clean = false; }
  ok(clean, 'و روی بدنه‌ی سالم خطا نمی‌دهد (self-check بیش از حد سخت نیست)');
}

console.log(`\n${fail ? '❌' : '✅'} ${pass} ادعا سبز، ${fail} قرمز`);
process.exit(fail ? 1 : 0);

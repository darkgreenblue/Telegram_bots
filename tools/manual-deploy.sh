#!/usr/bin/env bash
# 🛟 دیپلویِ دستی روی خودِ سرور — وقتی GitHub Actions در دسترس نیست.
#
# چرا این فایل هست: در ۲۰ آگوست ۲۰۲۶ کلِ Actionsِ حساب از کار افتاد (بیلینگ) و
# چون تنها مسیرِ رساندنِ کد به سرور همان `deploy.yml` بود، لانچِ آماده روی زمین ماند.
# این اسکریپت همان کاری را می‌کند که جابِ deploy می‌کرد، ولی از داخلِ خودِ سرور.
#
# ── چرا هیچ سکرتی لازم ندارد ──────────────────────────────────────────────────
# دو چیز از قبل روی سرور هستند و این اسکریپت به هیچ‌کدام دست نمی‌زند:
#   • credentialِ گیت (خودِ deploy.yml هم فقط `git pull --ff-only` می‌زند)
#   • فایل‌های `bots/*/.env` (دیپلوی فقط وقتی بازنویسی‌شان می‌کند که Secret ست باشد)
# پس این‌جا نه توکن لازم است نه کلید. همین باعث می‌شود اجرایش از کنسولِ ارائه‌دهنده‌ی
# VPS بی‌خطر باشد: هیچ رازی روی صفحه چاپ نمی‌شود.
#
# ── اجرا ─────────────────────────────────────────────────────────────────────
#   cd ~/voice2text && git pull --ff-only && bash tools/manual-deploy.sh
#
# آرگومان اختیاری: نامِ ربات‌هایی که باید ری‌لود شوند (پیش‌فرض: فقط tarot).
#   bash tools/manual-deploy.sh tarot voice2text
set -euo pipefail

cd "$(dirname "$0")/.."
BOTS=("$@")
[ ${#BOTS[@]} -eq 0 ] && BOTS=(tarot)

# 🛟 تورِ ایمنی: هر خروجِ ناموفق (از جمله `npm ci` که روی این سرور می‌تواند به
# registry.npmjs.org نرسد) نباید رباتِ **زنده و درآمدزا** را خاموش رها کند.
# بدونِ این trap، مسیرِ واقعی این بود: مهاجرت موفق ⟶ ربات stop ⟶ npm ci شکست ⟶
# `set -e` خروج ⟶ هیچ پروسه‌ای بالا نیست، و بدتر: گاردِ ارسالِ پیام همچنان سبز است،
# پس پیامِ انبوه با سه دکمه به یک رباتِ مرده اشاره می‌کرد.
restore_on_fail() {
  local code=$?
  [ $code -eq 0 ] && exit 0
  echo "❌ اسکریپت با کدِ $code شکست خورد — تلاش برای بالا نگه‌داشتنِ ربات‌ها"
  pm2 start ecosystem.config.cjs --only "$(IFS=,; echo "${BOTS[*]}")" 2>/dev/null || true
  pm2 list || true
  echo "⚠️ وضعیتِ بالا را چک کن. تا وقتی ربات online نیست، **پیامِ اطلاع‌رسانی را نفرست.**"
  exit $code
}
trap restore_on_fail EXIT

echo "📍 $(pwd)  ·  HEAD=$(git rev-parse --short HEAD)"

# ── بلوکِ یک‌باره‌ی «مهاجرتِ موجودیِ تومانی به الماس» این‌جا بود و **حذف شد** ──────
# مهاجرت اجرا شد و مهرش یک **ردیف در خودِ دیتابیس** است (`coin_v2` در جدولِ
# `migrations`)، پس طبق قاعده‌ی ثابتِ ریپو بلوکِ یک‌باره بعد از تأیید برداشته می‌شود.
# ⚠️ چرا فقط تمیزکاری نبود: شرطِ بلوک به یک **فایلِ** مارکر بند بود
# (`data/.coin-migration-done`) و همان الگویی است که پستمورتمِ v3.25.1 ردش کرد، چون
# فایل با بازسازیِ سرور یا restore از بکاپ (که فقط `*.db` دارد) از بین می‌رود. روی
# دیتابیسی که کدِ **امروز** ساخته باشد (سرورِ تازه، locale جدید) نرخ‌های تومانی معنی
# ندارند و `newBalanceFor` هر موجودیِ غیرصفر را به **۱۰٬۰۰۰ الماس** می‌برد. تنها چیزی
# که جلویش را می‌گرفت ردیفِ `coin_v2` بود که روی دیتابیسِ تازه وجود ندارد.
# اگر روزی واقعاً لازم شد (restore از بکاپِ قبل از ۱۴۰۵/۰۵/۳۰)، اسکریپت را **دستی** و
# آگاهانه اجرا کن، با `pm2 stop tarot` قبلش.

# ── وابستگی‌ها و ری‌لود ───────────────────────────────────────────────────────
for b in "${BOTS[@]}"; do
  if [ ! -f "bots/$b/.env" ]; then
    echo "⏭ bots/$b/.env نیست — $b رد شد"
    continue
  fi
  npm ci --prefix "bots/$b" --omit=dev
  pm2 startOrReload ecosystem.config.cjs --update-env --only "$b"
  echo "✅ $b دیپلوی شد"
done
pm2 save || true

echo
echo "---- وضعیت ----"
pm2 list
echo
echo "🎯 قدمِ بعدی (فقط بعد از تأییدِ چشمیِ وضعیتِ بالا):"
echo "   node tools/announce-tarot.mjs bots/tarot/data          # dry-run"
echo "   node tools/announce-tarot.mjs bots/tarot/data --send   # ارسالِ واقعی"

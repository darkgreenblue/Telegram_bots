#!/usr/bin/env node
// گاردِ «ادعای تصمیم‌ساز باید وضعیتِ منبعش را صادقانه بگوید».
//
// 🐛 باگی که این را لازم کرد (۱۴۰۵/۰۶/۰۹): در `I18N-MODEL-RESEARCH.md` نوشته شده بود
// «`gemini-2.5-flash` **طبق صفحه‌ی deprecationهای گوگل** ۱۶ اکتبر ۲۰۲۶ بازنشسته
// می‌شود». آن صفحه **هرگز خوانده نشده بود** (پراکسیِ محیط `ai.google.dev` را می‌بندد)
// و ادعا از خلاصه‌ی نتایجِ جستجو آمده بود. مالک صفحه‌ی واقعی را باز کرد: آن مدل هیچ
// تاریخِ خاموشی ندارد؛ تاریخِ ۲ اکتبر مالِ `gemini-2.5-flash-image` است که مدلِ دیگری
// است و ما استفاده‌اش نمی‌کنیم.
//
// ضررش فقط یک خطای واقعی نبود؛ آن ادعا به **پنج جای دیگر** تکثیر شد و یک «فوریت»
// ساختگی ساخت که چند تصمیمِ انتخابِ مدل را هدایت کرد.
//
// درس: مدلِ قوی و فکرِ بیشتر این را نمی‌گیرد، چون خطا در **استدلال** نبود، در
// **منبع** بود. تنها چیزی که می‌گیردش انضباطِ منبع است: ادعایی که به یک صفحه‌ی مرجع
// استناد می‌کند و آن صفحه باز نشده، باید همان‌جا برچسبِ «خوانده‌نشده» داشته باشد.
import { readFileSync, readdirSync } from 'fs';

let pass = 0; const errs = [];
const ok = (c, m) => { if (c) { pass++; console.log(`  ✅ ${m}`); } else { errs.push(m); console.log(`  ❌ ${m}`); } };

const DIR = new URL('../bots/tarot/', import.meta.url);
const DOCS = readdirSync(DIR).filter(f => /^I18N-.*\.md$/.test(f)).sort();

/* عبارت‌هایی که ادعا را به یک منبعِ رسمی می‌چسبانند. اگر یکی از این‌ها در سند باشد،
 * سند باید جایی وضعیتِ دسترسی را هم گفته باشد. عمداً کوچک و صریح است: هدف گرفتنِ
 * «طبق صفحه‌ی X» بدونِ هیچ اشاره‌ای به اینکه X خوانده شده یا نه. */
const CITES = [/طبق\s+صفحه/, /طبق\s+مستندات/, /بر\s?اساسِ?\s+صفحه/];
/* نشانه‌های صداقتِ منبع: یا گفته چه چیزی خوانده نشده، یا برچسبِ snippet دارد، یا
 * بخشِ محدودیت دارد. */
const HONEST = [/خوانده\s?نشد/, /snippet-only/, /محدودیت/, /تأییدنشده/, /باز نشد/, /بسته\s+است/];

console.log('▶ ادعاهای منبع‌دار وضعیتِ دسترسی را می‌گویند');
for (const f of DOCS) {
  const t = readFileSync(new URL(f, DIR), 'utf8');
  if (!CITES.some(r => r.test(t))) { continue; }
  ok(HONEST.some(r => r.test(t)),
    `${f}: به یک صفحه‌ی مرجع استناد می‌کند و وضعیتِ دسترسی را هم گفته`);
}

/* و ادعای مشخصی که ما را گاز گرفت: هیچ سندی نباید دوباره بگوید مدلِ رباتِ زنده
 * تاریخِ بازنشستگی دارد، مگر اینکه صریحاً بگوید آن ادعای قبلی غلط بود. */
console.log('\n▶ ادعای باطل‌شده‌ی بازنشستگی برنگشته');
for (const f of [...DOCS, 'CLAUDE.md']) {
  const t = readFileSync(new URL(f, DIR), 'utf8');
  const lines = t.split('\n');
  const bad = lines.filter((l) => /gemini-2\.5-flash/.test(l)
    && /بازنشست|تاریخِ انقضا|منقضی/.test(l)
    && !/غلط|باطل|تصحیح|نوشته بود|نسخه‌ی اول|ندارد|~~/.test(l));
  ok(bad.length === 0,
    `${f}: ادعای بازنشستگیِ gemini-2.5-flash بدونِ تصحیح تکرار نشده`
    + (bad.length ? ` (${bad.length} خط)` : ''));
}

console.log(errs.length ? `\n❌ ${errs.length} خطا` : `\n✅ انضباطِ منبع: ${pass} پاس، 0 خطا`);
process.exit(errs.length ? 1 : 0);

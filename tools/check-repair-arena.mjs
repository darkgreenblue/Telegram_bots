#!/usr/bin/env node
/* چکِ آرِنای تعمیر (`tools/repair-arena.mjs`).
 *
 * چرا لازم است: این ابزار قرار است پایه‌ی یک **تصمیمِ مدل** شود، و درسِ ثبت‌شده‌ی این
 * ریپو می‌گوید بیشترِ نتیجه‌های وارونه از باگِ خودِ ابزار آمده‌اند نه از مدل (بند ۹/۰ب).
 * پس خودِ ابزار قبل از اینکه عددی تولید کند تست می‌شود.
 *
 * چک **رفتاری** است: ابزار واقعاً روی یک فیکسچرِ کامیت‌شده در حالتِ `--fake` اجرا
 * می‌شود و خروجی‌اش سنجیده می‌شود.
 */
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';

let pass = 0; const errs = [];
const ok = (c, m) => { if (c) { pass++; console.log(`  ✅ ${m}`); } else { errs.push(m); console.log(`  ❌ ${m}`); } };

const run = (args, env = {}) => spawnSync(process.execPath,
  ['tools/repair-arena.mjs', ...args], { encoding: 'utf8', env: { ...process.env, ...env } });

console.log('\n▶ انتخابِ جمعیتِ نمونه');
const r = run(['--dir', 'tools/reading-lab/fixtures', '--fake', '--reps', '3']);
const out = `${r.stdout}\n${r.stderr}`;
ok(r.status === 0, `اجرا موفق است (کد ${r.status})`);
ok(/4 فال/.test(out), 'هر چهار ردیفِ فیکسچر خوانده می‌شوند');
ok(/2 فال ایرادِ تعمیرشدنی دارد/.test(out), 'دقیقاً دو ردیف واردِ آرِنا می‌شوند');
ok(/F1\.1 — evasion/.test(out), 'ردیفِ طفره‌رونده انتخاب می‌شود');

/* ⚠️ مهم‌ترین ادعای این فایل و دلیلِ وجودش: **نشتِ برچسب یک ضعفِ تعمیرشدنی نیست.**
 * ردیفِ F2 عیناً «حسِ ناگفته‌ات اینه» دارد و باید **انتخاب نشود**، چون `defects[]`
 * هیچ زبانی چنین ردیفی ندارد و مسیرِ تعمیر هرگز رویش شلیک نمی‌کند. اگر روزی کسی
 * چنین ردیفی اضافه کرد، این ادعا قرمز می‌شود و همان‌جا معلوم می‌شود که نتیجه‌ی
 * «عوض‌کردنِ مدلِ تعمیر روی نشتِ برچسب اثری ندارد» دیگر معتبر نیست. */
ok(!/F2\.1/.test(out), 'نشتِ برچسب واردِ آرِنا نمی‌شود (مسیرِ تعمیر نمی‌بیندش)');
ok(!/F3\.1/.test(out), 'فالِ سالم واردِ آرِنا نمی‌شود');

/* ═══ خاصیتی که کلِ اعتبارِ آرِنا به آن بند است ═══
 * آرِنا هر ورودی را چند بار و به چند بازو می‌دهد. اگر `applyFixes` ورودی را **عوض
 * کند**، تلاشِ دوم روی متنِ تعمیرشده‌ی تلاشِ اول می‌نشیند، هیچ ضعفی پیدا نمی‌کند، و
 * `fired` به‌جای ۳ می‌شود ۱ — یعنی نرخِ موفقیت مصنوعاً پایین می‌آید و بازویی که
 * **اول** اجرا شده جریمه می‌شود. سوگیریِ نامتقارن، بدترین نوعش.
 * امروز `applyFixes` خالص است و آرِنا به همین تکیه می‌کند. این ادعا همان تکیه‌گاه را
 * قفل می‌کند تا اگر روزی شکست، این‌جا صدا بدهد نه در یک عددِ گمراه‌کننده. */
console.log('\n▶ خلوصِ applyFixes (تکیه‌گاهِ بی‌کلون بودنِ آرِنا)');
{
  const { applyFixes } = await import('../bots/tarot/repair.js');
  const llm = { headline: 'الف', pattern: 'ب', reads: [{ text: 'ج' }], cards: [{ teaser: 'د' }] };
  const snap = JSON.stringify(llm);
  applyFixes(llm, [{ path: 'headline' }, { path: 'reads.0' }, { path: 'cards.0' }], ['۱', '۲', '۳']);
  ok(JSON.stringify(llm) === snap, 'applyFixes ورودی را دست نمی‌زند (وگرنه آرِنا بین تلاش‌ها تقلب می‌کند)');
}

console.log('\n▶ تکرارها مستقل‌اند');
for (const arm of ['google/gemini-2.5-flash', 'openai/gpt-5.6-luna']) {
  /* ⚠️ گزارش عمداً **دو** عدد دارد و هر دو ادعا می‌شوند: «فالِ کاملاً تمیز» و
   * «دستِ‌کم یک تکه». با سنجشِ تکه‌به‌تکه این دو از هم جدا شدند و چاپ‌کردنِ فقط یکی
   * یعنی خواننده عددی می‌بیند که معنی‌اش عوض شده و خبر ندارد. */
  const m = out.match(new RegExp(`── ${arm.replace(/[/.]/g, '\\$&')}[\\s\\S]*?شلیک: (\\d+)/(\\d+)[^\\n]*فالِ کاملاً تمیز: (\\d+)/(\\d+)[^\\n]*دستِ‌کم یک تکه: (\\d+)/(\\d+)`));
  ok(!!m, `بلوکِ گزارشِ «${arm}» هر دو عدد را دارد`);
  if (m) {
    ok(m[1] === '6' && m[2] === '6', `«${arm}» هر ۶ تلاش شلیک می‌کند (شد ${m[1]}/${m[2]})`);
    // F1 تک‌تکه است و تمیز می‌شود؛ F4 دوتکه است و تکه‌ی دومش رد می‌شود.
    ok(m[3] === '3', `«${arm}» فقط فالِ تک‌تکه را کاملاً تمیز می‌کند (شد ${m[3]}/6)`);
    ok(m[5] === '6', `«${arm}» در هر ۶ تلاش دستِ‌کم یک تکه را می‌گیرد (شد ${m[5]})`);
  }
}

/* ═══ شمارنده‌ی per نوع باید پرچمِ **خودِ تکه** را ببیند ═══
 *
 * 🐛 با سنجشِ تکه‌به‌تکه (v3.43.0) معنیِ `repaired` عوض شد: حالا یعنی «دستِ‌کم یک تکه»،
 * نه «فال تمیز شد». شمارنده‌ای که هنوز از روی `repaired` تکه‌ها را حساب کند، هر تکه‌ی
 * **ردشده** را هم موفق می‌شمارد — یعنی یک نرخِ موفقیتِ متورم، درست در ابزاری که قرار
 * است پایه‌ی تصمیمِ مدل باشد. F4 دقیقاً برای همین هست: تکه‌ی `evasion` تعمیر می‌شود و
 * تکه‌ی `pastTime` نه. */
console.log('\n▶ شمارنده‌ی per نوع، تکه‌به‌تکه است نه کلِ فراخوانی');
for (const arm of ['google/gemini-2.5-flash', 'openai/gpt-5.6-luna']) {
  const blk = out.split(`── ${arm}`)[1] || '';
  ok(/• evasion: 6\/6/.test(blk), `«${arm}» تکه‌ی تعمیرشده را موفق می‌شمارد`);
  ok(/• pastTime: 0\/3/.test(blk), `«${arm}» تکه‌ی ردشده را موفق **نمی‌شمارد**`);
}

console.log('\n▶ گاردهای ورودی');
{
  const noDir = run(['--fake']);
  // ⚠️ فقط کدِ خروج کافی نیست: بدونِ گارد هم `readdirSync('')` می‌ترکد و کد غیرصفر
  // می‌شود، پس آن ادعا جهشِ «گارد را بردار» را نمی‌گرفت. پیامِ صریح هم ادعا می‌شود.
  ok(noDir.status !== 0, 'بدونِ --dir با خطا می‌ایستد');
  ok(/--dir لازم است/.test(`${noDir.stdout}${noDir.stderr}`), 'و دلیلش را صریح می‌گوید');
}
const empty = run(['--dir', 'tools', '--fake']);
ok(empty.status === 0 && /هیچ ورودی‌ای نماند|ایرادِ تعمیرشدنی/.test(`${empty.stdout}`),
  'پوشه‌ی بی‌ورودی بی‌صدا و بدونِ خطا تمام می‌شود');

console.log(`\n${errs.length ? '❌' : '✅'} نتیجه: ${pass} پاس، ${errs.length} خطا`);
for (const e of errs) console.log(`   - ${e}`);
assert.equal(errs.length, 0, `${errs.length} خطای آرِنای تعمیر`);
